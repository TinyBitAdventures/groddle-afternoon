/**
 * Build the shared drop tables from Tiny Speck's GameServerJS (CC0).
 *
 * Reads:
 *   items/catalog_drop_tables.js   all 93 drop tables (keys are cumulative
 *                                  percent thresholds; entries are items,
 *                                  currants, favor, mood, energy, iMG or a
 *                                  nested table)
 *   items/<class>.js               name_single / name_plural / label / base
 *                                  cost of every item a table can give (the
 *                                  "You got 3 Cherries!" activity lines)
 *
 * Writes:
 *   public/js/drop-tables-data.js  frozen ES module: DROP_TABLES (rows sorted
 *                                  by threshold) and DROP_ITEMS (names, base
 *                                  cost, whether an icon exists)
 *
 * Run from spike root:  node build-drop-tables.mjs
 */

import vm from 'node:vm';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const AUDIT = join(process.env.HOME || '', 'Documents/glitch-audit');
const GSJS = process.env.GLITCH_GSJS || join(AUDIT, 'glitch-GameServerJS');
const ICONS = join(root, 'public/assets/sprites/icons');
const OUT = join(root, 'public/js/drop-tables-data.js');

const ctx = {};
vm.createContext(ctx);
vm.runInContext(`${readFileSync(join(GSJS, 'items/catalog_drop_tables.js'), 'utf8')}\n;this.__t = drop_tables;`, ctx);
const raw = ctx.__t;

const unq = (s) => s.replace(/\\\//g, '/').replace(/\\"/g, '"').replace(/\\'/g, "'");
const strVar = (src, name) => {
  const m = src.match(new RegExp(`^var ${name} = "((?:[^"\\\\]|\\\\.)*)";`, 'm'));
  return m ? unq(m[1]) : '';
};

const tables = {};
const itemIds = new Set();
for (const [id, table] of Object.entries(raw)) {
  // for (var drop_chance in table.drops): integer keys iterate ascending.
  const rows = Object.keys(table.drops)
    .map(Number)
    .sort((a, b) => a - b)
    .map((chance) => [chance, table.drops[chance].map((e) => {
      if (e.class_id) itemIds.add(e.class_id);
      if (e.class_id) return { item: e.class_id, count: Number(e.count) || 1 };
      if (e.drop_table) return { table: e.drop_table };
      if (e.currants) return { currants: Number(e.currants) };
      if (e.favor) return { favor: { giant: e.favor.giant, points: Number(e.favor.points) } };
      if (e.mood) return { mood: Number(e.mood) };
      if (e.energy) return { energy: Number(e.energy) };
      if (e.xp) return { xp: Number(e.xp) };
      return { unknown: JSON.parse(JSON.stringify(e)) };
    })]);
  tables[id] = { name: table.name || id, rows };
}

const items = {};
for (const id of [...itemIds].sort()) {
  const file = join(GSJS, 'items', `${id}.js`);
  const src = existsSync(file) ? readFileSync(file, 'utf8') : '';
  items[id] = {
    label: strVar(src, 'label') || id,
    single: strVar(src, 'name_single') || strVar(src, 'label') || id,
    plural: strVar(src, 'name_plural') || `${strVar(src, 'label') || id}s`,
    desc: strVar(src, 'description'),
    baseCost: Number(src.match(/^var base_cost = ([0-9.]+);/m)?.[1] || 0),
    art: existsSync(join(ICONS, `${id}.png`)),
  };
}

const header = `/**
 * GENERATED by build-drop-tables.mjs from GameServerJS
 * items/catalog_drop_tables.js and items/*.js (Tiny Speck, CC0).
 * Do not edit by hand.
 */

`;
writeFileSync(
  OUT,
  `${header}export const DROP_TABLES = Object.freeze(${JSON.stringify(tables)});\n\nexport const DROP_ITEMS = Object.freeze(${JSON.stringify(items)});\n`
);
const withArt = Object.values(items).filter((i) => i.art).length;
console.log(`wrote ${OUT}: ${Object.keys(tables).length} tables, ${Object.keys(items).length} items (${withArt} with icons)`);
