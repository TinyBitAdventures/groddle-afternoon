/**
 * G334: The Great Hog Haul between real players: the layout the realtime
 * server owns (the server's races.go + hoghaul.go). One course, laid out
 * exactly as game.js setupHogHaulWorld lays out the solo race on the same
 * street (the quest's imported cave, HOG_HAUL_STREET_ID; config_prod.js:896-903
 * names LHVLC8CI3Q62P8T, which is not archived):
 *   - the Pig Pen at world (-15, -875) (players/inc_games.js:2073 drops the
 *     penned Piggy there), on the ground;
 *   - 11 Pig Bait sacks and 8 loose Piggies from planStreetPlacements with the
 *     pen and the start reserved and the solo seed, so both modes stand them
 *     in the same places;
 *   - two start points beside the pen (solo's player spot, and its mirror for
 *     the second racer: config_prod.js start_points flank the pen the same way).
 * Each Piggy paces round its spot (game.js spawnHogHaulPiggy: range 42..105).
 *
 * Run from the game repo root:
 *   node tools/build-realtime-hoghaul.mjs          (write)
 *   node tools/build-realtime-hoghaul.mjs --check  (fail when stale)
 * Writes data/hoghaul.json in the realtime server repo (go:embed in its hoghaul.go;
 * found by tools/repos.mjs: GRODDLE_SERVER_DIR, else ../groddle-afternoon-server).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { loadStreetDataFromFs } from '../public/js/street-loader.js?v=d6cbbd5c';
import { isStandable, platformYAt, platformsScreen, resolveGround, streetWidth, worldToScreen } from '../public/js/street-model.js?v=23b926e5';
import { planStreetPlacements } from '../public/js/street-ecology.js?v=7e30da8f';
import { HOG_HAUL_GOAL, HOG_HAUL_STREET_ID } from '../public/js/hog-haul.js?v=50d2e072';
import { HOG_HAUL_TICKET } from '../public/js/races.js?v=df0576ad';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const streetsDir = join(root, 'public/assets/streets');
const outPath = serverPath('data', 'hoghaul.json');

const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v));
const r1 = (v) => Math.round(v);

/** game.js resolveGround: the surface under the feet, else the lowest standable platform across x. */
function groundAt(platforms, x, y, fallback) {
  const hit = resolveGround(platforms, x, y, 0, 16);
  if (hit) return hit.y;
  let best = null;
  for (const p of platforms) {
    if (!isStandable(p)) continue;
    const py = platformYAt(p, x, 8);
    if (py != null && (best == null || py > best)) best = py;
  }
  return best ?? fallback;
}

export async function hogHaulData() {
  const street = await loadStreetDataFromFs(HOG_HAUL_STREET_ID, streetsDir);
  const platforms = platformsScreen(street);
  const W = streetWidth(street);
  const penRaw = worldToScreen(street, -15, -875);
  const pen = { x: clamp(penRaw.x, 190, W - 190), y: groundAt(platforms, penRaw.x, penRaw.y + 10, penRaw.y) };
  const plan = planStreetPlacements(platforms, [
    { key: 'raceBaits', count: 11, clearance: 66 },
    { key: 'racePiggies', count: 8, clearance: 92 },
  ], {
    worldW: W,
    seed: `${HOG_HAUL_STREET_ID}:race-items`,
    reserved: [
      { ...pen, key: 'pig-pen', clearance: 210 },
      { x: pen.x - 145, y: pen.y, key: 'race-start', clearance: 105 },
    ],
  });
  const spawnAt = (dx) => {
    const x = clamp(pen.x + dx, 40, W - 40);
    return [r1(x), r1(groundAt(platforms, x, pen.y, pen.y))];
  };
  return {
    about: 'The Great Hog Haul for hoghaul.go in groddle-afternoon-server. Generated by tools/build-realtime-hoghaul.mjs from the street the game draws and game.js setupHogHaulWorld; do not edit by hand.',
    format: '{street, title, goal, spawns:[[x,y],[x,y]], pen:[x,y], baits:[[x,y]…], pigs:[[x,y,range]…]} in the street\'s screen pixels',
    street: HOG_HAUL_STREET_ID,
    title: HOG_HAUL_TICKET.title,
    goal: HOG_HAUL_GOAL,
    spawns: [spawnAt(-145), spawnAt(145)],
    pen: [r1(pen.x), r1(pen.y)],
    baits: (plan.groups.raceBaits || []).map((p) => [r1(p.x), r1(p.y)]),
    pigs: (plan.groups.racePiggies || []).map((p) => [r1(p.x), r1(p.y), Math.max(42, Math.min(105, Number(p.clearance) || 86))]),
  };
}

async function main() {
  requireServer();
  const out = await hogHaulData();
  const text = `${JSON.stringify(out)}\n`;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-hoghaul.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${out.baits.length} baits, ${out.pigs.length} piggies)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${out.baits.length} baits, ${out.pigs.length} piggies -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
