/**
 * G891: every Sloth in its own street's tree. For each street the location files give Sloths
 * (assets/content/street-ecology.json counts.npc_sloth: 37 streets, 84 Sloths), this runs the
 * sloth audit's placement rule (js/sloth-trees.js, place.py ported: the trunk and crown decos of
 * the street's own art) and writes public/js/sloth-spots-data.js, which street-ecology.js
 * MEASURED_NODE_SPOTS hands to resource-nodes-feature as each Sloth's spot. A street's rows are
 * left to right, so `npc_sloth:<i>` is the i-th tree from the left, for good.
 *
 * It prints the rule's flags (lift outside 150-260 px, no floor, a HIDE ME box wider than its
 * crown: "narrow", 8 since #746: check them by eye) and fails when a street's tree count is not its
 * Sloth count.
 *
 *   node tools/build-sloth-spots.mjs          write
 *   node tools/build-sloth-spots.mjs --check  exit 1 if stale or a count is off
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { slothSpotRow, slothTrees } from '../public/js/sloth-trees.js?v=a44a0ed8';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = 'public/js/sloth-spots-data.js';

/** PURE: { [tsid]: { label, want } } for every street whose location file has Sloths. */
export function slothStreets(ecology) {
  const out = {};
  for (const [tsid, row] of Object.entries(ecology?.streets || {}).sort(([a], [b]) => a.localeCompare(b))) {
    const want = Number(row?.counts?.npc_sloth) || 0;
    if (want > 0) out[tsid] = { label: row.label || tsid, want };
  }
  return out;
}

export function buildSlothSpots() {
  const ecology = JSON.parse(readFileSync(join(root, 'public/assets/content/street-ecology.json'), 'utf8'));
  const spots = {};
  const flags = [];
  const wrong = [];
  for (const [tsid, { label, want }] of Object.entries(slothStreets(ecology))) {
    const street = JSON.parse(readFileSync(join(root, 'public/assets/streets', `${tsid}.json`), 'utf8'));
    const trees = slothTrees(street);
    if (trees.length !== want) wrong.push(`${label} (${tsid}): ${trees.length} trees for ${want} Sloths`);
    trees.forEach((tree, i) => {
      if (tree.flags.length) flags.push(`${label} ${i}: ${tree.flags.join(', ')}`);
    });
    spots[tsid] = trees.map(slothSpotRow);
  }
  const rows = Object.entries(spots).map(([tsid, list]) => `  ${tsid}: Object.freeze([${list.map((r) => `[${r.join(', ')}]`).join(', ')}]),`);
  const text = `// Generated by tools/build-sloth-spots.mjs from the street art (js/sloth-trees.js): never edit by hand.
/**
 * G891: each Sloth's spot in its own street's tree, left to right (npc_sloth:<i> is the i-th):
 * [x, y, dir, floor, knockerX, knockerY] in street px (0, 0 = the street's top left). x, y is the
 * sloth's origin at its crown's lower edge, dir 1 right of the trunk or -1 left, floor the floor
 * under it (its hit box reaches down to it), knockerX, knockerY the Knocker's foot on the trunk.
 * street-ecology.js MEASURED_NODE_SPOTS reads them.
 */
export const SLOTH_SPOTS = Object.freeze({
${rows.join('\n')}
});
`;
  return { text, spots, flags, wrong };
}

function main() {
  const check = process.argv.includes('--check');
  const { text, spots, flags, wrong } = buildSlothSpots();
  const out = join(root, OUT);
  let before = '';
  try { before = readFileSync(out, 'utf8'); } catch { /* new */ }
  const sloths = Object.values(spots).reduce((n, list) => n + list.length, 0);
  if (flags.length) console.log(`flags (by eye): ${flags.join('; ')}`);
  if (wrong.length) console.error(`tree count is not the Sloth count: ${wrong.join('; ')}`);
  if (check) {
    if (before !== text || wrong.length) {
      console.error(`${OUT} is stale: run node tools/build-sloth-spots.mjs`);
      process.exit(1);
    }
    console.log(`sloth spots are current (${Object.keys(spots).length} streets, ${sloths} Sloths)`);
  } else {
    if (before !== text) writeFileSync(out, text);
    console.log(`${sloths} Sloths on ${Object.keys(spots).length} streets -> ${OUT}`);
    if (wrong.length) process.exit(1);
  }
}

// Run only as a script: tests import the helpers above without writing anything.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
