/**
 * #715: which street events a player's game may share with the street online (a Piano Party key, a
 * Gaare Grims stone), for the realtime server's streetsounds.go, which relays only an event its
 * street lists. From the game's own street files (public/assets/streets/<tsid>.json `events`, with a
 * puzzle street's repaired scripts from public/assets/content/puzzle-triggers.json laid over them as
 * puzzles-feature does), by js/street-sounds-mp.js streetSoundsFor: the events that play a sound for
 * every player there (play_sound all_players), arrivals, toy streets and streets another system runs
 * left out.
 *
 * Run from the game repo root:
 *   node tools/build-realtime-street-sounds.mjs          (write)
 *   node tools/build-realtime-street-sounds.mjs --check  (fail when stale)
 * Writes data/street-sounds.json in the realtime server repo (go:embed in its streetsounds.go;
 * found by tools/repos.mjs: GRODDLE_SERVER_DIR, else ../groddle-afternoon-server).
 */

import { readFileSync, readdirSync } from 'node:fs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';
import { streetSoundsFor } from '../public/js/street-sounds-mp.js?v=c9c290e0';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const streetsDir = join(root, 'public', 'assets', 'streets');
const repairsPath = join(root, 'public', 'assets', 'content', 'puzzle-triggers.json');
const outPath = serverPath('data', 'street-sounds.json');

/** Every street that shares a sound: { tsid: [event, ...] }, sorted. */
export function streetSoundsData() {
  const repairs = JSON.parse(readFileSync(repairsPath, 'utf8')).streets || {};
  const files = readdirSync(streetsDir).filter((f) => /^[A-Z0-9_]+\.json$/.test(f) && f !== 'index.json').sort();
  const streets = {};
  for (const f of files) {
    const tsid = f.slice(0, -5);
    const s = JSON.parse(readFileSync(join(streetsDir, f), 'utf8'));
    const events = { ...(s.events || {}), ...(repairs[tsid]?.events || {}) };
    const names = streetSoundsFor(tsid, events);
    if (names.length) streets[tsid] = names;
  }
  return {
    about: 'Street events whose sound a player shares with the street (#715), for streetsounds.go in groddle-afternoon-server. Generated by tools/build-realtime-street-sounds.mjs from public/assets/streets; do not edit by hand.',
    format: 'streets[tsid] = [event]: events that play a sound for every player there (play_sound all_players); a street_sound naming another event is dropped',
    streets,
  };
}

async function main() {
  requireServer();
  const out = streetSoundsData();
  const text = `${JSON.stringify(out, null, 1)}\n`;
  const n = Object.values(out.streets).reduce((k, list) => k + list.length, 0);
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-street-sounds.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${Object.keys(out.streets).length} streets, ${n} events)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${Object.keys(out.streets).length} streets, ${n} events -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
