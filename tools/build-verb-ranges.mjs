#!/usr/bin/env node
/**
 * Build public/js/verb-ranges-data.js: how near a verb needs you (js/walk-over.js).
 *
 * The server measured each itemstack verb from the player's feet to the thing's
 * (main.js doVerb 2939-2967): 300 px, or the verb's own "proximity_override", and
 * no check at all for a verb with "disable_proximity" (a shrine's Check Favor, a
 * furniture Buy, a Butterfly's Massage). This reads both flags from every
 * verbs.<id> = {...} block in Tiny Speck's GameServerJS items (CC0; each file
 * carries its parents' verbs, "defined by ...").
 *
 * Pickup is left out of the table: 810 of the 936 classes with a pickup verb set
 * it to 800 (the rest kept 300), and js/walk-over.js takes 800 for every pickup.
 *
 *   node tools/build-verb-ranges.mjs [path/to/glitch-GameServerJS] [--check]
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const GSJS = process.argv.slice(2).find((a) => !a.startsWith('--')) || join(ROOT, '..', 'glitch-GameServerJS');
const OUT = join(ROOT, 'public/js/verb-ranges-data.js');
const check = process.argv.includes('--check');

const itemsDir = join(GSJS, 'items');
if (!existsSync(itemsDir)) throw new Error(`build-verb-ranges: no ${itemsDir}`);

const table = {};
for (const file of readdirSync(itemsDir).filter((f) => f.endsWith('.js')).sort()) {
  const classId = file.slice(0, -3);
  const src = readFileSync(join(itemsDir, file), 'utf8');
  const re = /verbs\.(\w+)\s*=\s*\{([\s\S]*?)\n\};/g;
  let m;
  while ((m = re.exec(src))) {
    const [, verb, body] = m;
    const off = /"disable_proximity"\s*:\s*true/.test(body);
    const over = body.match(/"proximity_override"\s*:\s*(\d+)/);
    if (!off && !over) continue;
    const range = off ? 0 : Number(over[1]);
    if (verb === 'pickup' && range === 800) continue;
    (table[classId] ||= {})[verb] = range;
  }
}

const lines = [
  '// Generated by tools/build-verb-ranges.mjs from glitch-GameServerJS items/*.js',
  '// (each verb\'s "proximity_override" in px, 0 for "disable_proximity"). Do not edit.',
  'export const VERB_RANGES = Object.freeze({',
  ...Object.keys(table).sort().map((c) => `  ${JSON.stringify(c)}: Object.freeze(${JSON.stringify(Object.fromEntries(Object.entries(table[c]).sort()))}),`),
  '});',
  '',
];
const out = lines.join('\n');
if (check) {
  const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (have !== out) {
    console.error('build-verb-ranges: public/js/verb-ranges-data.js is stale');
    process.exit(1);
  }
  console.log(`build-verb-ranges: ok (${Object.keys(table).length} classes)`);
} else {
  writeFileSync(OUT, out);
  console.log(`build-verb-ranges: wrote ${Object.keys(table).length} classes`);
}
