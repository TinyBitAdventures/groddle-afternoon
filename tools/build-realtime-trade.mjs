/**
 * Multiplayer phase 4, trading: which items two players may trade and how
 * many fit in one trade slot, for the realtime server (the realtime server's trade.go,
 * go:embed) and the trade window (js/features/trade-feature.js), both from
 * the same file so they never disagree.
 *
 * Source rules (glitch-GameServerJS, read as text, nothing evaluated):
 *  - Only pack items trade: classes with the takeable parent or include
 *    (items/<id>.js parent_classes, //#include), not is_hidden, not retired
 *    (an onLoad replaceWith).
 *  - The client refused items tagged no_trade (TradeManager.as:38
 *    TRADE_TAGS_TO_EXCLUDE, TradeDialog.as:1061 and 1083), with the tags of
 *    items/<id>.js `var tags` plus items/catalog_tags.js item_tags.
 *  - Soulbound items cannot be traded (inc_trading.js:473-479). The classes
 *    that bind themselves to whoever carries them are play_cube
 *    (items/play_cube.js:121-140) and greeter_twig (items/greeter_twig.js:
 *    214-219); both are also tagged no_trade. Default home furniture was
 *    soulbound per stack (players/inc_furniture.js:97-132); the remake does
 *    not track stacks, so furniture trades like any item.
 *  - One trade slot is one stack: a slot holds at most the class's stackmax
 *    (MakingSlot.as:162 min(has, stackmax, MAX_COUNT 9999)).
 *  - The remake's pack has no bags with contents, so the non-empty bag rule
 *    (inc_trading.js:465-471) never applies.
 *  - A tool carries its points left across a trade (the source moved the
 *    itemstack with its tool_state). pts is the class's points capacity
 *    (js/tools.js TOOL_CONDITION_CATALOG, from items/<tool>.js
 *    points_capacity), so the server clamps a sent r to what the tool holds.
 *  - food: the class includes include/food.js (is_food, include/food.js:1),
 *    which a street Piggy eats off the ground (items/npc_piggy.js
 *    onContainerItemAdded 1393-1411, onFoodPathing 1482-1500; the server's
 *    drops.go and objects_pigs.go).
 *
 * Run from the game repo root:
 *   node tools/build-realtime-trade.mjs           writes the server repo's data/trade.json and public/assets/content/trade-items.json
 *   node tools/build-realtime-trade.mjs --check   exits 1 when either file is stale
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { readItemTags, readItems } from './inventory/gsjs-data.mjs';
import { TOOL_CONDITION_CATALOG } from '../public/js/tools.js?v=woodcutting-test-3';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const GSJS = join(root, '..', 'glitch-GameServerJS');
export const OUT_SERVER = serverPath('data', 'trade.json');
export const OUT_CLIENT = join(root, 'public/assets/content/trade-items.json');

/** MakingSlot.as:25 MAX_COUNT: no slot holds more, whatever the stackmax. */
export const SLOT_MAX = 9999;
/** Classes that soulbind to their carrier (see the header). */
export const SOULBOUND = Object.freeze(['play_cube', 'greeter_twig']);

function scalar(text, name) {
  const m = new RegExp(`^var ${name}\\s*=\\s*("(?:[^"\\\\]|\\\\.)*"|[^;\\n]+)`, 'm').exec(text);
  if (!m) return '';
  const raw = m[1].trim();
  if (raw.startsWith('"')) {
    try { return JSON.parse(raw); } catch { return raw.slice(1, -1); }
  }
  return raw;
}

/** The trade table: tradeable classes with their slot limit and names, and the pack items that may not trade, with why. */
export function tradeTable(gsjs = GSJS) {
  const items = readItems(gsjs, readItemTags(gsjs));
  const tradeable = {};
  const untradeable = {};
  for (const it of items) {
    if (!it.takeable || it.hidden || it.retiredTo) continue;
    if (SOULBOUND.includes(it.id)) {
      untradeable[it.id] = 'soulbound';
      continue;
    }
    if (it.tags.includes('no_trade')) {
      untradeable[it.id] = 'no_trade';
      continue;
    }
    const text = readFileSync(join(gsjs, 'items', `${it.id}.js`), 'utf8');
    const stackmax = Math.floor(Number(scalar(text, 'stackmax'))) || 1;
    const name = scalar(text, 'name_single') || scalar(text, 'label') || it.id;
    const plural = scalar(text, 'name_plural') || name;
    tradeable[it.id] = { max: Math.max(1, Math.min(SLOT_MAX, stackmax)), name, plural };
    const pts = Math.floor(Number(TOOL_CONDITION_CATALOG[it.id]?.capacity) || 0);
    if (pts > 0) tradeable[it.id].pts = pts;
    if (it.include.some((i) => /(^|\/)include\/food\.js$/.test(i))) tradeable[it.id].food = true;
  }
  const sort = (o) => Object.fromEntries(Object.keys(o).sort().map((k) => [k, o[k]]));
  return {
    _doc: 'Generated by tools/build-realtime-trade.mjs from glitch-GameServerJS items (do not edit). items: tradeable class -> slot limit, names, (tools) pts, the points capacity, and food (include/food.js, a Piggy eats it); untradeable: pack items that may not trade, and why.',
    slots: 6, // TradeDialog.as:50 MAX_TRADE_SLOTS
    items: sort(tradeable),
    untradeable: sort(untradeable),
  };
}

export function tradeJson(gsjs = GSJS) {
  return `${JSON.stringify(tradeTable(gsjs), null, 0).replace(/,"(?=[a-z0-9_]+":\{"max")/g, ',\n"')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  requireServer();
  const text = tradeJson();
  if (process.argv.includes('--check')) {
    let stale = false;
    for (const p of [OUT_SERVER, OUT_CLIENT]) {
      let have = '';
      try { have = readFileSync(p, 'utf8'); } catch { /* missing */ }
      if (have !== text) {
        console.error(`${p} is stale: run node tools/build-realtime-trade.mjs`);
        stale = true;
      }
    }
    process.exit(stale ? 1 : 0);
  }
  for (const p of [OUT_SERVER, OUT_CLIENT]) {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, text);
  }
  const t = tradeTable();
  console.log(`trade table: ${Object.keys(t.items).length} tradeable, ${Object.keys(t.untradeable).length} untradeable`);
}
