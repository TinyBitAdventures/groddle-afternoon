#!/usr/bin/env node
/**
 * Register G528: the floors a player can fall onto and not get off with a plain jump, for
 * /stuck's one-time hint (features/slash-commands-feature.js). The builder's reach graph
 * (js/builder/reach-graph.js) runs from every shipped arrival at the three plain jumps a character
 * has as it levels (js/imagination.js SOURCE_DEFAULT_PHYSICS and the High Jumper cards), and each
 * line that traps at one of them is listed with the highest of the three it still traps at.
 *
 * Left out: a swim street or one whose events change physics (the model is only approximate
 * there, as tools/ecology/build-unreached-floors.mjs), a street with no exit or nothing arriving,
 * and the puzzle streets (assets/content/puzzle-triggers.json: their lost boxes are rebuilt, and
 * the model doesn't know them). Teleporters aren't in the model, so Level 3 West's and Mada
 * Tamaha's pits stay listed: the boxes are invisible, and the hint is still true.
 *
 * A ladder a jump lifts you to counts as a way out (reach graph jumpGrab): Up jumps and takes it.
 *
 * Writes public/js/street-traps-data.js.
 *
 *   node tools/ecology/build-street-traps.mjs            # all streets (a few minutes, all cores)
 *   node tools/ecology/build-street-traps.mjs --check    # fails when the file is stale
 *   node tools/ecology/build-street-traps.mjs --only GLI107JLRU11EM2 --print
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { cpus } from 'node:os';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { fileURLToPath } from 'node:url';
import { GAME_DIR } from '../repos.mjs';
import { reachStreet, streetBuff } from '../../public/js/builder/reach-graph.js?v=b8634e9a';

/** A new character, High Jumper I, High Jumper II (js/imagination.js). */
export const TRAP_JUMPS = Object.freeze([0.7105, 0.907, 1]);
const OUT = join(GAME_DIR, 'public/js/street-traps-data.js');
const json = (p) => JSON.parse(readFileSync(p, 'utf8'));
const twin = (tsid) => String(tsid || '').slice(1);

function approximate(street) {
  if (streetBuff(street).approximate) return true;
  return Object.values(street.events || {}).flat().some((a) => a?.type === 'physics');
}

/** PURE: a street's trap lines { [line]: highest TRAP_JUMPS entry it traps at }, or null. */
export function trapLinesOf(street, arrivals) {
  if (!arrivals.length || approximate(street)) return null;
  const seen = new Set();
  const arr = arrivals.filter((a) => {
    const k = `${Math.round(a.x)},${Math.round(a.y)}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
  const base = streetBuff(street).buff;
  const out = {};
  for (const jump of TRAP_JUMPS) {
    const r = reachStreet(street, arr, { jumpGrab: true, buff: { ...base, jump: (base.jump ?? 1) * jump } });
    if (!r.arrivals.some((a) => a.stands) || !r.targets.length) return null;
    for (const t of r.traps) out[t.line] = jump;
  }
  return Object.keys(out).length ? out : null;
}

function runJobs(jobs) {
  return jobs.map(([tsid, path, arrivals]) => {
    try {
      return { tsid, lines: trapLinesOf(json(path), arrivals) };
    } catch (err) {
      return { tsid, lines: null, error: String(err?.message || err) };
    }
  });
}

/** PURE: the generated module's text. */
export function renderTraps(section) {
  const rows = Object.keys(section).sort().map((tsid) => {
    const lines = Object.keys(section[tsid]).sort().map((line) => `${JSON.stringify(line)}:${section[tsid][line]}`).join(',');
    return `  ${JSON.stringify(tsid)}: {${lines}},`;
  });
  return `// GENERATED by tools/ecology/build-street-traps.mjs: don't edit.
// Floors a plain jump doesn't get off: { [street tsid]: { [line id]: the highest jump multiplier it traps at } }.
export const STREET_TRAPS = Object.freeze({
${rows.join('\n')}
});
`;
}

const RUN = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (!isMainThread && workerData?.streetTraps) {
  parentPort.postMessage(runJobs(workerData.jobs));
} else if (RUN) {
  const args = process.argv.slice(2);
  const arg = (name, dflt = null) => {
    const i = args.indexOf(name);
    return i >= 0 ? args[i + 1] : dflt;
  };
  const only = arg('--only') ? new Set(arg('--only').split(',')) : null;
  const { shippedStreetFiles } = await import('../builder/validator-context.mjs');
  const { shippedArrivals } = await import('../builder/calibrate.mjs');
  const puzzles = new Set(Object.keys(json(join(GAME_DIR, 'public/assets/content/puzzle-triggers.json')).streets || {}).map(twin));
  const files = shippedStreetFiles();
  const { byStreet } = shippedArrivals(files);
  const jobs = files.filter(([t]) => (!only || only.has(t)) && !puzzles.has(twin(t))).map(([t, p]) => [t, p, byStreet.get(twin(t)) || []]);
  const n = Math.max(1, Math.min(Number(arg('--workers', cpus().length - 1)), jobs.length));
  const buckets = Array.from({ length: n }, () => []);
  jobs.sort((a, b) => b[2].length - a[2].length).forEach((j, i) => buckets[i % n].push(j));
  const results = (await Promise.all(buckets.map((b) => new Promise((resolve, reject) => {
    const w = new Worker(fileURLToPath(import.meta.url), { workerData: { jobs: b, streetTraps: true } });
    w.once('message', resolve);
    w.on('error', reject);
  })))).flat();
  const errors = results.filter((r) => r.error);
  if (errors.length) console.error(`errors: ${JSON.stringify(errors)}`);
  const section = {};
  for (const r of results) if (r.lines) section[r.tsid] = r.lines;
  if (args.includes('--print') || only) {
    console.log(JSON.stringify(section, null, 1));
    process.exit(0);
  }
  const text = renderTraps(section);
  if (args.includes('--check')) {
    if (readFileSync(OUT, 'utf8') !== text) {
      console.error('public/js/street-traps-data.js is stale: run node tools/ecology/build-street-traps.mjs');
      process.exit(1);
    }
    console.log(`street traps are current (${Object.keys(section).length} streets)`);
  } else {
    writeFileSync(OUT, text);
    console.log(`${Object.keys(section).length} streets with traps -> public/js/street-traps-data.js`);
  }
}
