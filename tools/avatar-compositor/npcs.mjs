#!/usr/bin/env node
/**
 * The other Glitches' sheets: every NPC_GLITCH_ROSTER look
 * (js/npc-glitch-looks.js buildNpcLooks, from assets/avatar/catalog.json with
 * a fixed seed) composited by js/avatar-compositor.js in Chromium, like the
 * default look (build.mjs render), at 1x and the NPC hires scale.
 *
 *   node tools/avatar-compositor/npcs.mjs                  # bake + js/npc-glitch-sheets.js
 *   node tools/avatar-compositor/npcs.mjs --preview <dir>  # also one stand frame per look (PNG)
 *   node tools/avatar-compositor/npcs.mjs --check          # fail when the module is stale
 *
 * NPCs skip the AFK doze (idleSleepy). Their hires sheets are 2x, not the
 * player's 3x: several are on screen at once and every one loads idle4 as
 * its stand, so 2x keeps a Glitch at 4/9 of the 3x texture memory (about
 * 12 MB for base + idle4 instead of 28 MB) while still filling a DPR 2
 * screen far better than 1x. Lossy WebP (q90, sharp YUV, lossless alpha):
 * 40% of the lossless size, PSNR about 38 dB on the busiest sheet, no
 * visible change at play scale.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { expandCatalog, resolveLook } from '../../public/js/avatar-looks.js?v=64fab53e';
import { buildNpcLooks } from '../../public/js/npc-glitch-looks.js?v=664e5f24';
import { execFileSync } from 'node:child_process';
import { withPage } from './build.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '../..');
const PUBLIC = join(ROOT, 'public');
const OUT = join(PUBLIC, 'assets/sprites/avatar/npc');
const MODULE = join(PUBLIC, 'js/npc-glitch-sheets.js');
/** Sheets an NPC Glitch has (no AFK doze). */
export const NPC_SHEETS = Object.freeze(['base', 'jump', 'climb', 'happy', 'surprise', 'angry', 'idle4', 'idle1', 'idle2', 'idle3']);
export const NPC_HIRES = 2;

const args = process.argv.slice(2);
const opt = (name) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : null;
};

/** One sheet as lossy WebP (see above); returns the file written. */
function saveSheet(stem, dataUrl) {
  mkdirSync(dirname(stem), { recursive: true });
  const png = `${stem}.png`;
  const webp = `${stem}.webp`;
  writeFileSync(png, Buffer.from(dataUrl.split(',')[1], 'base64'));
  execFileSync('cwebp', ['-quiet', '-q', '90', '-alpha_q', '100', '-m', '6', '-sharp_yuv', png, '-o', webp]);
  rmSync(png);
  return webp;
}

function loadCatalog() {
  return expandCatalog(JSON.parse(readFileSync(join(PUBLIC, 'assets/avatar/catalog.json'), 'utf8')));
}

function moduleText(entries) {
  const body = entries.map((e) => `  ${JSON.stringify(e.id)}: Object.freeze(${JSON.stringify(e)}),`).join('\n');
  return `/**
 * The other Glitches' baked sheets (generated by
 * tools/avatar-compositor/npcs.mjs; do not edit by hand). One look per
 * js/npc-glitch-looks.js NPC_GLITCH_ROSTER name (fields from buildNpcLooks),
 * composited from Tiny Speck's CC0 avatar SWFs at 1x and ${NPC_HIRES}x
 * (\`hires\`, resolution from the @${NPC_HIRES}x name). Same sheet layout as
 * js/avatar-vector-sheets.js; feetY/midX: the standing pose's feet.
 */
export const NPC_GLITCH_HIRES = ${NPC_HIRES};

export const NPC_GLITCH_SHEETS = Object.freeze({
${body}
});
`;
}

/** The roster entries without the sheet sizes (what --check compares). */
const fieldsOnly = (entries) => entries.map(({ id, name, seed, fields }) => ({ id, name, seed, fields }));

async function bake() {
  const catalog = loadCatalog();
  const looks = buildNpcLooks(catalog);
  const previewDir = opt('preview');
  const results = await withPage(async (page) => {
    const out = [];
    for (const l of looks) {
      const look = resolveLook(l.fields, catalog);
      const t = Date.now();
      const sheets = await page.evaluate(async ({ look: lk, scales, only }) => window.renderLook(lk, scales, only), { look, scales: [1, NPC_HIRES], only: NPC_SHEETS });
      const preview = previewDir ? await page.evaluate(async (lk) => window.renderPreview(lk, 801, 240, 320), look) : null;
      out.push({ l, sheets, preview, ms: Date.now() - t });
    }
    return out;
  });
  const entries = [];
  let bytes = 0;
  for (const { l, sheets, preview, ms } of results) {
    const dir = join(OUT, l.id);
    rmSync(dir, { recursive: true, force: true });
    mkdirSync(dir, { recursive: true });
    const defs = {};
    for (const name of NPC_SHEETS) {
      const r = sheets[name];
      const f1 = saveSheet(join(dir, name), r[1]);
      const fh = saveSheet(join(dir, `${name}@${NPC_HIRES}x`), r[NPC_HIRES]);
      bytes += statSync(f1).size + statSync(fh).size;
      const d = r.def;
      defs[name] = { file: relative(dir, f1), hires: relative(dir, fh), cells: d.cells, fw: d.fw, fh: d.fh, cols: d.cols, rows: d.rows, feetY: d.feetY, midX: d.midX };
    }
    if (preview) {
      mkdirSync(previewDir, { recursive: true });
      writeFileSync(join(previewDir, `${l.id}.png`), Buffer.from(preview.split(',')[1], 'base64'));
    }
    entries.push({ id: l.id, name: l.name, seed: l.seed, fields: l.fields, dir: `${relative(PUBLIC, dir)}/`, sheets: defs });
    console.log(`  ${l.name}: seed ${l.seed} (${l.attempts} draws), ${ms} ms`);
  }
  writeFileSync(MODULE, moduleText(entries));
  console.log(`wrote ${relative(ROOT, MODULE)}; ${entries.length} looks, ${(bytes / 2 ** 20).toFixed(1)} MB of sheets`);
}

async function check() {
  const { NPC_GLITCH_SHEETS } = await import(`${MODULE}?t=${Date.now()}`);
  const want = fieldsOnly(buildNpcLooks(loadCatalog()));
  const have = fieldsOnly(Object.values(NPC_GLITCH_SHEETS));
  if (JSON.stringify(want) !== JSON.stringify(have)) {
    console.error('js/npc-glitch-sheets.js is stale: rerun node tools/avatar-compositor/npcs.mjs');
    process.exit(1);
  }
  for (const e of Object.values(NPC_GLITCH_SHEETS)) {
    for (const s of Object.values(e.sheets)) {
      for (const f of [s.file, s.hires]) if (!existsSync(join(PUBLIC, e.dir, f))) throw new Error(`missing ${e.dir}${f}`);
    }
  }
  console.log('npc looks up to date');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  (args.includes('--check') ? check() : bake()).catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
