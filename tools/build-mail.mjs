/**
 * Mail between real players (register G478): the base cost of every class
 * the ledger can carry, for the postage the site charges (groddle-afternoon-site
 * data/mail.json, read by src/LedgerMail.php). The game charges from the same
 * table (js/player-mail.js reads store-catalog.js ITEM_BASE_COSTS), so the
 * price a player sees is the price the site takes.
 *
 * Source: players/inc_mail.js mail_get_message_cost 1295-1312 prices an
 * attached stack at 10% of itemstack.getBaseCost() times the count (at least
 * 1); getBaseCost is the class's base_cost (items/<id>.js), here
 * store-catalog.js ITEM_BASE_COSTS, the table tools/build-economy.mjs reads
 * for the ledger's values. Classes with no base cost are left out (0: the
 * stack costs the minimum 1).
 *
 * What a letter may hold (#217, Austin 2026-11-12 "allow it, as Glitch did"):
 * every pack item but those Glitch refused. Its server refused only a bag
 * with things in it (inc_mail.js mail_can_send 26-29; the game checks that
 * before it asks, js/player-mail.js composeRefusal); its client refused items
 * tagged no_mail and stacks soulbound to the sender (AbstractMailUI.as
 * isDroppable 60-74) and never let the hogtied piggy be dragged in
 * (RESTRICTED_ITEMS, AbstractMailUI.as:22 and 80). no_trade was no reason:
 * the Crabpod Headphones (crabphones.js 102) went by mail. So:
 *  - refused: class -> no_mail (items/catalog_tags.js 2198-2201), soulbound
 *    (the trade table's, tools/build-realtime-trade.mjs SOULBOUND),
 *    restricted, or bag (a wrapped Gift Box always holds something);
 *  - unpriced: the pack items the ledger does not carry (the trade table's
 *    untradeable, no_trade) that may still go, moved through the saves by the
 *    letter's receipts (the site's LedgerMail unpricedShort);
 *  - base: the base cost of everything that may go.
 *
 * Run from the game repo root:
 *   node tools/build-mail.mjs           writes the site repo's data/mail.json
 *   node tools/build-mail.mjs --check   exits 1 when it is stale
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireSite, sitePath } from './repos.mjs';
import { ITEM_BASE_COSTS } from '../public/js/store-catalog.js?v=74b56af3';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const TRADE = join(root, 'public/assets/content/trade-items.json');
export const OUT = sitePath('data', 'mail.json');

/** items/catalog_tags.js 2198-2201: the classes tagged no_mail (also items/conch.js 579, faded_heart.js 121). */
export const NO_MAIL = Object.freeze(['conch', 'faded_heart']);
/** AbstractMailUI.as:22 RESTRICTED_ITEMS: never dragged into a letter (onPackDragStart 80). */
export const MAIL_RESTRICTED = Object.freeze(['hogtied_piggy']);
/**
 * A bag that always has things in it (mail_can_send 26-29): a wrapped Gift Box is the box and what
 * was wrapped (bag_gift_box_wrapped; its contents are the gifts slice's, which a letter cannot carry).
 */
export const MAIL_FULL_BAGS = Object.freeze(['bag_gift_box_wrapped']);

export function mailTable() {
  const trade = JSON.parse(readFileSync(TRADE, 'utf8'));
  const refused = {};
  for (const c of NO_MAIL) refused[c] = 'no_mail';
  for (const [c, why] of Object.entries(trade.untradeable || {})) if (why === 'soulbound') refused[c] = 'soulbound';
  for (const c of MAIL_RESTRICTED) refused[c] = 'restricted';
  for (const c of MAIL_FULL_BAGS) refused[c] = 'bag';
  const unpriced = Object.keys(trade.untradeable || {}).filter((c) => !refused[c] && !trade.items[c]).sort();
  const base = {};
  for (const c of [...Object.keys(trade.items), ...unpriced].sort()) {
    if (refused[c]) continue;
    const cost = Number(ITEM_BASE_COSTS[c]) || 0;
    if (cost > 0) base[c] = cost;
  }
  return {
    _doc: 'Generated by the game repo\'s tools/build-mail.mjs from store-catalog.js ITEM_BASE_COSTS and the trade table (do not edit). base: mailable class -> base_cost, for the postage of an attached stack (inc_mail.js mail_get_message_cost 1295-1312); a class not listed costs 0. unpriced: pack classes the ledger does not carry (no_trade) that a letter may still hold (#217). refused: class -> why a letter may not hold it (no_mail, soulbound, restricted: AbstractMailUI.as; bag: inc_mail.js mail_can_send 26-29). G478.',
    base,
    unpriced,
    refused: Object.fromEntries(Object.keys(refused).sort().map((c) => [c, refused[c]])),
  };
}

export function mailJson() {
  const t = mailTable();
  const rows = Object.entries(t.base).map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`).join(',\n');
  return `{"_doc":${JSON.stringify(t._doc)},\n"base":{\n${rows}},\n"unpriced":${JSON.stringify(t.unpriced)},\n"refused":${JSON.stringify(t.refused)}}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  requireSite();
  const text = mailJson();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (have !== text) {
      console.error(`${OUT} is stale: run node tools/build-mail.mjs`);
      process.exit(1);
    }
    process.exit(0);
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`mail table: ${Object.keys(mailTable().base).length} classes with a base cost, ${mailTable().unpriced.length} unpriced, ${Object.keys(mailTable().refused).length} refused`);
}
