/**
 * Mail between real players (register G478): the base cost of every class
 * the ledger can carry, for the postage the site charges (groddle-afternoon-site
 * data/mail.json, read by src/LedgerMail.php). The game charges from the same
 * table (js/player-mail.js reads store-catalog.js ITEM_BASE_COSTS), so the
 * price a player sees is the price the site takes.
 *
 * Source: players/inc_mail.js mail_get_message_cost 1295-1312 prices an
 * attached stack at 10% of itemstack.getBaseCost() times the count (at least
 * 1); getBaseCost is the class's base_cost (items/<id>.js), here
 * store-catalog.js ITEM_BASE_COSTS, the table tools/build-economy.mjs reads
 * for the ledger's values. Classes with no base cost are left out (0: the
 * stack costs the minimum 1). Only what the ledger carries (the tradeable
 * classes of public/assets/content/trade-items.json) can be mailed.
 *
 * Run from the game repo root:
 *   node tools/build-mail.mjs           writes the site repo's data/mail.json
 *   node tools/build-mail.mjs --check   exits 1 when it is stale
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireSite, sitePath } from './repos.mjs';
import { ITEM_BASE_COSTS } from '../public/js/store-catalog.js?v=79d4de8a';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const TRADE = join(root, 'public/assets/content/trade-items.json');
export const OUT = sitePath('data', 'mail.json');

export function mailTable() {
  const trade = JSON.parse(readFileSync(TRADE, 'utf8'));
  const base = {};
  for (const c of Object.keys(trade.items).sort()) {
    const cost = Number(ITEM_BASE_COSTS[c]) || 0;
    if (cost > 0) base[c] = cost;
  }
  return {
    _doc: 'Generated by the game repo\'s tools/build-mail.mjs from store-catalog.js ITEM_BASE_COSTS and the trade table (do not edit). base: tradeable class -> base_cost, for the postage of an attached stack (inc_mail.js mail_get_message_cost 1295-1312); a class not listed costs 0. G478.',
    base,
  };
}

export function mailJson() {
  const t = mailTable();
  const rows = Object.entries(t.base).map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`).join(',\n');
  return `{"_doc":${JSON.stringify(t._doc)},\n"base":{\n${rows}}}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  requireSite();
  const text = mailJson();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (have !== text) {
      console.error(`${OUT} is stale: run node tools/build-mail.mjs`);
      process.exit(1);
    }
    process.exit(0);
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  console.log(`mail table: ${Object.keys(mailTable().base).length} classes with a base cost`);
}
