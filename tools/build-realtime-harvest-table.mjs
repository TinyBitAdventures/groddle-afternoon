/**
 * Pot Luck Day's Harvest Table (G982, G1015b): what the realtime server's harvest_table.go lets a
 * player lay, the same classes the game takes (js/pot-luck-feast.js layableKind), so a lay the game
 * refuses is refused online too (root issue R4: the server took any food before).
 *
 *  - dishes: dishClasses(public/assets/content/recipes.json): Harvest Stuffing, Pot's harvest dishes
 *    (HARVEST_DISHES) and every output of a cooking tool's recipe (COOKING_TOOLS).
 *  - crops: cropClasses(js/garden.js SEED_CATALOG): what a garden seed grows, Glitch's crops
 *    (items/<crop>.js is_crop, produced_by_class seed_*).
 *
 * Run from the game repo root:
 *   node tools/build-realtime-harvest-table.mjs          (write)
 *   node tools/build-realtime-harvest-table.mjs --check  (fail when stale)
 * Writes data/harvest-table.json in the realtime server repo (go:embed in its harvest_table.go;
 * found by tools/repos.mjs: GRODDLE_SERVER_DIR, else ../groddle-afternoon-server).
 */

import { readFileSync } from 'node:fs';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { cropClasses, dishClasses } from '../public/js/pot-luck-feast.js?v=971888be';
import { SEED_CATALOG } from '../public/js/garden.js?v=a7c6f521';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = serverPath('data', 'harvest-table.json');

export function harvestTableData() {
  const recipes = JSON.parse(readFileSync(join(root, 'public/assets/content/recipes.json'), 'utf8'));
  return {
    about: 'What the Harvest Table takes, for harvest_table.go in groddle-afternoon-server. Generated by tools/build-realtime-harvest-table.mjs from public/js/pot-luck-feast.js (dishClasses over public/assets/content/recipes.json, cropClasses over js/garden.js SEED_CATALOG); do not edit by hand.',
    format: 'dishes and crops: sorted item classes; a lay is taken when its class is in either',
    dishes: [...dishClasses(recipes)].sort(),
    crops: [...cropClasses(SEED_CATALOG)].sort(),
  };
}

async function main() {
  requireServer();
  const out = harvestTableData();
  const text = `${JSON.stringify(out)}\n`;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-harvest-table.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${out.dishes.length} dishes, ${out.crops.length} crops)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${out.dishes.length} dishes, ${out.crops.length} crops -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
