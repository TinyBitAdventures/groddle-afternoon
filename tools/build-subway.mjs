/**
 * The Ur subway's data and streets (register row G115).
 *
 * 1. public/js/subway-line.js: config_prod.js transit_instances.subway_1 as a
 *    frozen table (stations in Red Line order from Groddle Forest Junction),
 *    with each station's and the train's own name and hub from
 *    inc_data_maps_prod.js and the surface street each one connects to.
 * 2. The 12 stations and the train car as street JSON (builders in
 *    public/js/subway.js), listed in assets/streets/index.json. The stations'
 *    stairs arrive in front of their surface street's subway entrance. The
 *    surface streets' own doors are linked at runtime by
 *    features/subway-feature.js, so no imported street JSON changes.
 *
 *   node tools/build-subway.mjs          write
 *   node tools/build-subway.mjs --check  exit 1 if anything is stale
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readMapLabels, readTransitInstances } from './subway-source.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const streetsDir = join(root, 'public/assets/streets');
const lineFile = join(root, 'public/js/subway-line.js');
const check = process.argv.includes('--check');
const stale = [];

const g = (tsid) => `G${String(tsid).slice(1)}`;
const index = JSON.parse(readFileSync(join(streetsDir, 'index.json'), 'utf8'));
const hubNames = {};
for (const row of Object.values(index.streets)) if (row.hubId && row.hubName && !hubNames[row.hubId]) hubNames[row.hubId] = row.hubName;

// 1. The line table.
const cfg = readTransitInstances().subway_1;
const ids = [];
for (let id = 1; ids.length < Object.keys(cfg.stations).length; id = cfg.stations[id].next_stop) {
  if (ids.includes(id)) throw new Error(`the Red Line loops back to ${id} early`);
  ids.push(id);
}
const labels = readMapLabels([cfg.template_tsid, ...ids.map((id) => cfg.stations[id].tsid)]);
const stations = ids.map((id) => {
  const s = cfg.stations[id];
  const surface = index.streets[g(s.connects_to)] || null;
  const own = labels[s.tsid] || {};
  return {
    id,
    name: s.name,
    tsid: s.tsid,
    streetTsid: g(s.tsid),
    label: own.label || `${s.name} Subway Station`,
    hubId: own.hubId || null,
    hubName: hubNames[own.hubId] || '',
    previous_stop: s.previous_stop,
    next_stop: s.next_stop,
    connects_to: s.connects_to,
    surfaceStreetTsid: surface ? g(s.connects_to) : null,
    surfaceLabel: surface?.label || '',
    surfaceHubId: surface?.hubId || null,
    x: s.x,
    y: s.y,
    map_pos: s.map_pos,
  };
});
const { stations: _omit, ...head } = cfg;
const line = {
  ...head,
  car: {
    tsid: cfg.template_tsid,
    streetTsid: g(cfg.template_tsid),
    label: labels[cfg.template_tsid]?.label || 'Subway Train',
    hubId: labels[cfg.template_tsid]?.hubId || null,
    hubName: hubNames[labels[cfg.template_tsid]?.hubId] || '',
    x: cfg.x,
    y: cfg.y,
  },
  stations,
};

const freeze = (value, pad = '') => {
  if (Array.isArray(value)) {
    if (value.every((v) => typeof v !== 'object' || v === null)) return `Object.freeze(${JSON.stringify(value)})`;
    return `Object.freeze([\n${value.map((v) => `${pad}  ${freeze(v, `${pad}  `)},`).join('\n')}\n${pad}])`;
  }
  if (value && typeof value === 'object') {
    return `Object.freeze({\n${Object.entries(value).map(([k, v]) => `${pad}  ${/^[A-Za-z_]\w*$/.test(k) ? k : JSON.stringify(k)}: ${freeze(v, `${pad}  `)},`).join('\n')}\n${pad}})`;
  }
  return JSON.stringify(value);
};
const lineText = [
  '// Generated by tools/build-subway.mjs from glitch-GameServerJS config_prod.js',
  '// transit_instances.subway_1 (stations in Red Line order) and inc_data_maps_prod.js',
  '// (station and train names and hubs). Do not edit.',
  `export const SUBWAY_LINE = ${freeze(line)};`,
  '',
].join('\n');

function put(file, text) {
  let before = '';
  try {
    before = readFileSync(file, 'utf8');
  } catch {
    /* new file */
  }
  if (before === text) return;
  stale.push(file.slice(root.length + 1));
  if (!check) writeFileSync(file, text);
}

put(lineFile, lineText);

// 2. Streets. In --check mode the builders read the line table as it would be written.
if (check && stale.length) {
  console.log(`stale: ${stale.join(', ')}`);
  process.exit(1);
}
const subway = await import(pathToFileURL(join(root, 'public/js/subway.js')).href);
const missing = [];
const streets = [];
for (const station of subway.STATIONS) {
  let surfaceDoor = null;
  if (station.surfaceStreetTsid) {
    const surface = JSON.parse(readFileSync(join(streetsDir, `${station.surfaceStreetTsid}.json`), 'utf8'));
    surfaceDoor = (surface.doors || []).find((d) => d.connect?.tsid === station.tsid) || null;
    if (!surfaceDoor) missing.push(`${station.surfaceStreetTsid} has no door to ${station.tsid}`);
  } else {
    missing.push(`${station.name}: surface street ${station.connects_to} is not imported`);
  }
  streets.push(subway.stationStreet(station, { surfaceDoor }));
}
streets.push(subway.carStreet());

let indexChanged = false;
for (const street of streets) {
  put(join(streetsDir, `${street.tsid}.json`), `${JSON.stringify(street)}\n`);
  const row = subway.subwayIndexEntry(street);
  if (JSON.stringify(index.streets[street.tsid]) !== JSON.stringify(row)) {
    index.streets[street.tsid] = row;
    indexChanged = true;
  }
}
if (indexChanged) {
  stale.push('public/assets/streets/index.json');
  if (!check) writeFileSync(join(streetsDir, 'index.json'), `${JSON.stringify(index, null, 2)}\n`);
}

if (missing.length) console.log(`missing: ${missing.join('; ')}`);
console.log(`${check ? 'stale' : 'wrote'}: ${stale.length ? stale.join(', ') : 'nothing'}`);
if (check && stale.length) process.exit(1);
