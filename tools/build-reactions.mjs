/**
 * The reaction set for the realtime server and the site (Austin 2026-11-04: the boards' reactions are
 * the chat's). One set, public/js/chat-reactions.js REACTIONS, copied as JSON so the three never drift:
 *   - groddle-afternoon-server data/reactions.json (go:embed, reactions.go reactionKeys: the keys the
 *     server takes, in order);
 *   - groddle-afternoon-site data/reactions.json (src/CommunityText.php reads it: the boards' and the
 *     report messages' reactions).
 *
 * Run from the game repo root:
 *   node tools/build-reactions.mjs           writes both repos' files
 *   node tools/build-reactions.mjs --check   exits 1 when one is stale
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, requireSite, serverPath, sitePath } from './repos.mjs';
import { NAMES_SHOWN, REACTIONS } from '../public/js/chat-reactions.js?v=e2c21ad4';

/** The set as the twins read it: key, glyph, label and art (a site path, '' for none) in the chat's order. */
export function reactionsJson() {
  const set = REACTIONS.map((r) => ({ key: r.key, glyph: r.glyph, label: r.label, art: r.art ? `/${r.art}` : '' }));
  return `${JSON.stringify({ _doc: "Generated by the game repo's tools/build-reactions.mjs from public/js/chat-reactions.js (do not edit).", namesShown: NAMES_SHOWN, reactions: set }, null, 2)}\n`;
}

/** The site's copy. */
export const reactionsFile = () => sitePath('data', 'reactions.json');
/** The realtime server's copy. */
export const serverReactionsFile = () => serverPath('data', 'reactions.json');

/** Every file this writes and what it should hold. */
export function reactionsOutputs() {
  const text = reactionsJson();
  return [
    [serverReactionsFile(), text],
    [reactionsFile(), text],
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  requireServer();
  requireSite();
  const outs = reactionsOutputs();
  if (process.argv.includes('--check')) {
    let stale = 0;
    for (const [file, text] of outs) {
      let have = '';
      try { have = readFileSync(file, 'utf8'); } catch { /* missing */ }
      if (have !== text) {
        console.error(`${file} is stale: run node tools/build-reactions.mjs`);
        stale += 1;
      }
    }
    process.exit(stale ? 1 : 0);
  }
  for (const [file, text] of outs) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  console.log(`reactions: ${REACTIONS.length} -> server and site`);
}
