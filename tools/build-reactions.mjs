/**
 * The reaction set for the site's Community boards (Austin 2026-11-04: the boards' reactions are the
 * chat's). One set, public/js/chat-reactions.js REACTIONS (what the realtime server's reactions.go
 * takes), copied as JSON to groddle-afternoon-site data/reactions.json (src/CommunityText.php reads
 * it), so the boards and the chat never drift.
 *
 * Run from the game repo root:
 *   node tools/build-reactions.mjs           writes the site's file
 *   node tools/build-reactions.mjs --check   exits 1 when it is stale
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireSite, sitePath } from './repos.mjs';
import { NAMES_SHOWN, REACTIONS } from '../public/js/chat-reactions.js?v=d65d555b';

/** The set as the site reads it: key, glyph, label and art (a site path, '' for none) in the chat's order. */
export function reactionsJson() {
  const set = REACTIONS.map((r) => ({ key: r.key, glyph: r.glyph, label: r.label, art: r.art ? `/${r.art}` : '' }));
  return `${JSON.stringify({ _doc: "Generated by the game repo's tools/build-reactions.mjs from public/js/chat-reactions.js (do not edit).", namesShown: NAMES_SHOWN, reactions: set }, null, 2)}\n`;
}

export const reactionsFile = () => sitePath('data', 'reactions.json');

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  requireSite();
  const text = reactionsJson();
  const file = reactionsFile();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(file, 'utf8'); } catch { /* missing */ }
    if (have !== text) {
      console.error(`${file} is stale: run node tools/build-reactions.mjs`);
      process.exit(1);
    }
    process.exit(0);
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
  console.log(`reactions: ${REACTIONS.length} -> site`);
}
