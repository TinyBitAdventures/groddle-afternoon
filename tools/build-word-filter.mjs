/**
 * The word filter's list for the realtime server and the site (the remake's
 * own addition, Austin 2026-11-02; the original Glitch had no swear filter).
 * One list, public/js/word-filter-list.js, copied as JSON so the three never
 * drift:
 *   - groddle-afternoon-server data/word-filter.json (go:embed, wordfilter.go)
 *     and testdata/word-filter-vectors.json (wordfilter_test.go), the shared
 *     cases from tests/fixtures/word-filter-vectors.json;
 *   - groddle-afternoon-site data/word-filter.json (src/WordFilter.php).
 *
 * Run from the game repo root:
 *   node tools/build-word-filter.mjs           writes both repos' files
 *   node tools/build-word-filter.mjs --check   exits 1 when one is stale
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, requireSite, serverPath, sitePath, GAME_DIR } from './repos.mjs';
import { WORD_FILTER } from '../public/js/word-filter-list.js?v=20da9845';

export const VECTORS = join(GAME_DIR, 'tests', 'fixtures', 'word-filter-vectors.json');

/** The list as the twins read it: one key a line. */
export function wordFilterJson() {
  const lines = ['{', `"_doc":${JSON.stringify("Generated by the game repo's tools/build-word-filter.mjs from public/js/word-filter-list.js (do not edit; the rule is in js/word-filter.js and its twins). stems take a suffix, exact words take none, inside words match anywhere in a word, exceptions are never filtered.")},`];
  const keys = Object.keys(WORD_FILTER);
  keys.forEach((k, i) => lines.push(`${JSON.stringify(k)}:${JSON.stringify(WORD_FILTER[k])}${i < keys.length - 1 ? ',' : ''}`));
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

/** Every file this writes and what it should hold. */
export function wordFilterOutputs() {
  const list = wordFilterJson();
  return [
    [serverPath('data', 'word-filter.json'), list],
    [serverPath('testdata', 'word-filter-vectors.json'), readFileSync(VECTORS, 'utf8')],
    [sitePath('data', 'word-filter.json'), list],
  ];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  requireServer();
  requireSite();
  const outs = wordFilterOutputs();
  if (process.argv.includes('--check')) {
    let stale = 0;
    for (const [file, text] of outs) {
      let have = '';
      try { have = readFileSync(file, 'utf8'); } catch { /* missing */ }
      if (have !== text) {
        console.error(`${file} is stale: run node tools/build-word-filter.mjs`);
        stale += 1;
      }
    }
    process.exit(stale ? 1 : 0);
  }
  for (const [file, text] of outs) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  console.log(`word filter: ${WORD_FILTER.stems.length} stems, ${WORD_FILTER.exact.length} exact, ${WORD_FILTER.inside.length} inside, ${WORD_FILTER.exceptions.length} exceptions -> server and site`);
}
