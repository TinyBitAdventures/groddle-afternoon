/**
 * Multiplayer Feats (G345): the shared Feat everyone playing works toward
 * for one day, for the realtime server (groddle-afternoon-server feats.go,
 * go:embed data/feats.json). Written from the game's own rules
 * (public/js/solo-feats.js, the fifteen production Feats and their personal
 * goals; public/js/feats-mp.js, the multiplayer goals, schedule, pace and
 * rewards), so the Feat panel and the server never disagree.
 *
 * What it carries:
 *  - the schedule: the Glitch calendar's epoch, a run's 24 hours, the wired
 *    Feats in game_day order (feats-mp.js SCHEDULE), the game day's length
 *    (a streak counts once per street per game day) and quick_on_your_feat's
 *    30 minutes;
 *  - per wired Feat: its title, epic, the three goals (feats-mp.js GOALS),
 *    the pace (MP_PACE) and the acts a report must name (MP_ACTS), and
 *    whether the game counts its first contribution itself (the Last Feat
 *    chain's feats:contributed);
 *  - every production Feat's epic, wired or not (inc_feats.js:311 counts the
 *    whole list), and the rewards (doBreakIt's, the rocks by place, the
 *    top_26 and Cigar places).
 *
 * Run from the game repo root:
 *   node tools/build-realtime-feats.mjs           writes the server repo's data/feats.json
 *   node tools/build-realtime-feats.mjs --check   exits 1 when it is stale
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';
import { FEAT_BY_ID, SOLO_FEATS } from '../public/js/solo-feats.js?v=e026b67b';
import { GAME_DAY_MS } from '../public/js/game-day.js?v=3095e05b';
import {
  CIGAR_PLACES,
  LARGE_PLACES,
  MP_ACTS,
  MP_ORDER,
  MP_PACE,
  MP_REWARD,
  QUICK_MS,
  ROCK_LARGE,
  ROCK_MEDIUM,
  ROCK_SMALL,
  RUN_EPOCH_MS,
  RUN_MS,
  TOP_PLACES,
  epicSizes,
  mpGoals,
} from '../public/js/feats-mp.js?v=3aa606d6';

export const OUT_SERVER = serverPath('data', 'feats.json');

/** The server's table from the game's rules. */
export function featTable() {
  const feats = {};
  for (const id of MP_ORDER) {
    const f = FEAT_BY_ID[id];
    const p = MP_PACE[id];
    if (!p) throw new Error(`feats-mp.js MP_PACE has no row for ${id}`);
    const acts = {};
    for (const [act, a] of Object.entries(MP_ACTS[id] || {})) acts[act] = { n: a.n, ...(a.dedupe ? { dedupe: a.dedupe } : {}) };
    feats[id] = {
      title: f.title,
      epic: f.epic_id || 0,
      ...mpGoals(id),
      pace: { n: p.n, everyMs: p.everyMs, burst: p.burst },
      ...(Object.keys(acts).length ? { acts } : {}),
      ...(f.contributionCountedElsewhere ? { elsewhere: true } : {}),
    };
  }
  return {
    _doc: "Generated by tools/build-realtime-feats.mjs from the game's public/js/solo-feats.js and feats-mp.js (do not edit). order: the Feats that take turns, one a run of runMs from epochMs; feats: goals (the minimum, the bonus, the supermegabonus), pace (n every everyMs, a bucket of burst), acts (a report's fixed amount and dedupe); epics: how many production Feats each epic has; reward: what a contributor gets when the minimum goal was met.",
    epochMs: RUN_EPOCH_MS,
    runMs: RUN_MS,
    gameDayMs: GAME_DAY_MS,
    quickMs: QUICK_MS,
    order: [...MP_ORDER],
    feats,
    epics: epicSizes(),
    // The Feats that never take a turn (solo-feats.js `mp` ones do, G172).
    unwired: SOLO_FEATS.filter((f) => !MP_ORDER.includes(f.id)).map((f) => f.id),
    reward: {
      xp: MP_REWARD.xp,
      currants: MP_REWARD.currants,
      mood: MP_REWARD.mood,
      energy: MP_REWARD.energy,
      favor: MP_REWARD.favor.map((f) => ({ giant: f.giant, points: f.points })),
      small: ROCK_SMALL,
      medium: ROCK_MEDIUM,
      large: ROCK_LARGE,
      largePlaces: LARGE_PLACES,
      topPlaces: TOP_PLACES,
      cigarPlaces: CIGAR_PLACES,
    },
  };
}

export function featJson() {
  const t = featTable();
  const lines = [];
  const keys = Object.keys(t).filter((k) => k !== 'feats');
  lines.push('{');
  for (const k of keys) lines.push(`${JSON.stringify(k)}:${JSON.stringify(t[k])},`);
  lines.push('"feats":{');
  const ids = Object.keys(t.feats);
  ids.forEach((id, i) => lines.push(`${JSON.stringify(id)}:${JSON.stringify(t.feats[id])}${i < ids.length - 1 ? ',' : ''}`));
  lines.push('}');
  lines.push('}');
  return `${lines.join('\n')}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  requireServer();
  const text = featJson();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT_SERVER, 'utf8'); } catch { /* missing */ }
    if (have !== text) {
      console.error(`${OUT_SERVER} is stale: run node tools/build-realtime-feats.mjs`);
      process.exit(1);
    }
    process.exit(0);
  }
  mkdirSync(dirname(OUT_SERVER), { recursive: true });
  writeFileSync(OUT_SERVER, text);
  const t = JSON.parse(text);
  console.log(`feats: ${t.order.length} Feats take turns, ${Object.keys(t.epics).length} epics`);
}
