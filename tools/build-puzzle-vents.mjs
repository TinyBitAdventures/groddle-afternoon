// Rebuild the underwater vents (Jal/Samudra) into assets/content/puzzle-triggers.json.
//
// 35 swimming streets keep `upvent`/`downvent`/`vent` event scripts (strong
// upward pushes: gravity x-4..-11 for 0.4-3.2 s), but the Collision-triggered
// Event Boxes that fired them were not archived (0-6 per street survive as
// bare objrefs). Where a street still shows its currents, it does so with
// WindCurl / WindFog decos (the animated_fx swirl; its PNG frame is blank, so
// the remake draws rising bubbles instead): Daksina Tom has 3 boxes and 3
// curls, the rest at least one curl per surviving box. Each curl becomes a
// body box over its rotated bounds that fires the street's up-vent while the
// avatar is inside (repeating, so a long column keeps pushing).
//
// Run from the spike root after build-street-events.mjs:
//   node tools/build-puzzle-vents.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { streetOwner } from '../public/js/location-events.js?v=61e0c5d3';

const root = new URL('../public/', import.meta.url);
const dataUrl = new URL('assets/content/puzzle-triggers.json', root);
const streetsDir = new URL('assets/streets/', root);
const data = JSON.parse(readFileSync(dataUrl, 'utf8'));

const rotatedBounds = (d, ax, ay, sx, sy) => {
  const a = ((d.r || 0) * Math.PI) / 180;
  const w = d.w * sx;
  const h = d.h * sy;
  const pts = [[-w / 2, 0], [w / 2, 0], [w / 2, -h], [-w / 2, -h]].map(([px, py]) => [
    ax + px * Math.cos(a) - py * Math.sin(a),
    ay + px * Math.sin(a) + py * Math.cos(a),
  ]);
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  return { x0: Math.min(...xs), x1: Math.max(...xs), y0: Math.min(...ys), y1: Math.max(...ys) };
};

let streets = 0;
let vents = 0;
const skipped = [];
for (const file of readdirSync(streetsDir).filter((f) => /^G[A-Z0-9]+\.json$/.test(f))) {
  const street = JSON.parse(readFileSync(new URL(file, streetsDir), 'utf8'));
  const events = street.events || {};
  const ventEvent = events.upvent ? 'upvent' : events.vent ? 'vent' : null;
  if (!ventEvent) continue;
  if (streetOwner(street.tsid)) {
    skipped.push(`${street.label} (owned)`);
    continue;
  }
  const mg = (street.layers || []).find((l) => l.id === 'middleground');
  const W = street.bounds.r - street.bounds.l;
  const H = street.bounds.b - street.bounds.t;
  const triggers = [];
  for (const layer of street.layers || []) {
    const isMg = layer.id === 'middleground';
    const sx = !isMg && mg?.w && layer.w ? mg.w / layer.w : 1;
    const sy = !isMg && mg?.h && layer.h ? mg.h / layer.h : 1;
    for (const d of layer.decos || []) {
      if (!/^Wind(Curl|Fog)$/.test(d.sprite)) continue;
      const ax = isMg ? d.x - street.bounds.l : d.x * sx;
      const ay = isMg ? d.y - street.bounds.t : d.y * sy;
      const b = rotatedBounds(d, ax, ay, sx, sy);
      const w = Math.max(90, Math.round(b.x1 - b.x0));
      const h = Math.max(160, Math.round(b.y1 - b.y0));
      const x = Math.round((b.x0 + b.x1) / 2);
      const y = Math.min(H, Math.round(b.y1 + 20));
      if (x < 0 || x > W) continue;
      triggers.push({
        id: `vent${triggers.length + 1}`,
        x,
        y,
        w,
        h: h + 20,
        body: true,
        repeatMs: 450,
        bubbles: true,
        onEnter: [ventEvent],
        why: `${d.sprite} current (layer ${layer.id}${isMg ? '' : `, scaled x${sx.toFixed(2)}`}, anchor ${Math.round(ax)},${Math.round(ay)}, ${d.w}x${d.h} rotated ${d.r || 0}°): its rotated bounds, firing ${ventEvent} again every 450 ms while the avatar swims inside.`,
      });
    }
  }
  if (!triggers.length) {
    skipped.push(`${street.label} (no current decos)`);
    continue;
  }
  const prev = data.streets[street.tsid] || {};
  data.streets[street.tsid] = {
    ...prev,
    name: street.label,
    vents: true,
    sourcePhysics: false,
    emptyEcology: false,
    triggers,
    quoins: prev.quoins || [],
    ventsWhy: 'Generated by tools/build-puzzle-vents.mjs from the street\'s WindCurl/WindFog decos.',
  };
  streets += 1;
  vents += triggers.length;
}
writeFileSync(dataUrl, `${JSON.stringify(data, null, 1)}\n`);
console.log(JSON.stringify({ streets, vents, skipped }, null, 1));
