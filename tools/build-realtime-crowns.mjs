/**
 * G334: the Game of Crowns arena the realtime server referees between real
 * players (the realtime server's crowns.go). It writes what the server must
 * own to decide who holds the crown, tags, locks and the winner from the
 * positions players report, never from what a client says happened:
 *   - the play line in the arena's screen coords (games_it_game_is_started,
 *     players/inc_games.js 843-859: y >= -1390, put through playLineScreenY
 *     with the archived street's bounds);
 *   - the four starts and the four Crown Game Locks (js/game-of-crowns.js,
 *     the same spots solo uses);
 *   - the reaches: a tag (crowns-feature tick, CROWNS_TAG_DISTANCE and
 *     CROWNS_TAG_REACH_Y) and a lock touch (CROWNS_LOCK_REACH);
 *   - the clock and the rules: 60 s to win, the 1 s tag lock, the 4 s lock
 *     pickup and its 12 s respawn (items/crown_game_lock.js), the 4 s
 *     countdown, the winner's 200 iMG and 50 currants (games_end_it_game
 *     671-674) and the seats (config_prod.js:1281 it_game min_players 4,
 *     max_players 5, min_retry_players 3).
 *
 * Run from the game repo root:
 *   node tools/build-realtime-crowns.mjs          (write)
 *   node tools/build-realtime-crowns.mjs --check  (fail when stale)
 * Writes data/crowns.json in the realtime server repo (go:embed in its
 * crowns.go; found by tools/repos.mjs: GRODDLE_SERVER_DIR, else
 * ../groddle-afternoon-server).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import {
  CROWNS_COUNTDOWN_MS,
  CROWNS_LOCK_POINTS,
  CROWNS_LOCK_REACH,
  CROWNS_LOCK_RESPAWN_MS,
  CROWNS_PICKUP_LOCK_MS,
  CROWNS_PLAYERS,
  CROWNS_START_POINTS,
  CROWNS_STREET,
  CROWNS_TAG_DISTANCE,
  CROWNS_TAG_LOCK_MS,
  CROWNS_TAG_REACH_Y,
  CROWNS_TITLE,
  CROWNS_WIN_MS,
  CROWNS_WIN_REWARD,
  playLineScreenY,
} from '../public/js/game-of-crowns.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = serverPath('data', 'crowns.json');

/** config_prod.js:1281 shared_instances.it_game min_retry_players. */
export const CROWNS_RETRY_PLAYERS = 3;

const pt = (p) => [Math.round(p.x), Math.round(p.y)];

export function crownsData() {
  const street = JSON.parse(readFileSync(join(root, 'public', 'assets', 'streets', `${CROWNS_STREET}.json`), 'utf8'));
  return {
    about: 'The Game of Crowns arena for crowns.go in groddle-afternoon-server. Generated by tools/build-realtime-crowns.mjs from public/js/game-of-crowns.js and the archived street; do not edit by hand.',
    format: 'screen coords of the arena street; ms; players {min,max,retry}; reward {xp,currants}',
    street: CROWNS_STREET,
    title: CROWNS_TITLE,
    playLineY: Math.round(playLineScreenY(street)),
    starts: CROWNS_START_POINTS.map(pt),
    locks: CROWNS_LOCK_POINTS.map(pt),
    tag: { x: CROWNS_TAG_DISTANCE, y: CROWNS_TAG_REACH_Y },
    lockReach: { x: CROWNS_LOCK_REACH.x, y: CROWNS_LOCK_REACH.y },
    winMs: CROWNS_WIN_MS,
    tagLockMs: CROWNS_TAG_LOCK_MS,
    pickupLockMs: CROWNS_PICKUP_LOCK_MS,
    lockRespawnMs: CROWNS_LOCK_RESPAWN_MS,
    countdownMs: CROWNS_COUNTDOWN_MS,
    players: { min: CROWNS_PLAYERS.min, max: CROWNS_PLAYERS.max, retry: CROWNS_RETRY_PLAYERS },
    reward: { xp: CROWNS_WIN_REWARD.xp, currants: CROWNS_WIN_REWARD.currants },
  };
}

async function main() {
  requireServer();
  const text = `${JSON.stringify(crownsData())}\n`;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-crowns.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`crowns arena -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
