/**
 * G853, #392: Visiting Stones where the Eleven players' 2012 snaps show them. Glitch set every stone
 * by hand (visiting_stone.js; "Visiting Stones can typically be found in \"dead-end locations\" of
 * most regions", 202) and the 2012 location files keep only that a street has one, so the planner put
 * them anywhere on the street: half on the half with the signposts, a median 2,300 px from the dead end.
 * The spawn audit (2026-11-16) matched our own CC0 stone art against the snaps of the 105 stone streets
 * they cover and found 103 (stone-spots.json, hand-kept with its method): 102 of them within 1,200 px
 * of the street's signpost-free end.
 *
 * This seats each spot on the floor under it: of the standable lines at the spot's x, the one nearest
 * its y, at most SEAT_PX away (the art matched to the pixel, so a stone sits on its floor), with both
 * ends of the stone's footprint (street-ecology.js PLACEMENT_FOOTPRINTS.furnitureStone) on floor
 * (shrine-pictures.mjs seatOnFloor). It writes public/js/stone-spots-data.js, which
 * street-furniture.js stoneSpotRow pins the street's stone to and street-ecology.js
 * streetReservedSpots keeps every planned thing clear of.
 *
 *   node tools/snap-placements/stone-spots.mjs          write
 *   node tools/snap-placements/stone-spots.mjs --check  exit 1 if stale or a spot has no floor
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { platformsScreen } from '../../public/js/street-model.js?v=a9a05f9d';
import { PLACEMENT_FOOTPRINTS } from '../../public/js/street-ecology.js?v=da5177b2';
import { seatOnFloor } from './shrine-pictures.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
/** How far (street px) a measured stone's foot may sit off the floor it is seated on. */
export const STONE_SEAT_PX = 40;

/** PURE: the seated spot [x, y] for a measured stone on a street's platforms, or null. */
export function seatStone(platforms, [x, y]) {
  const fy = seatOnFloor(platforms, x, y, PLACEMENT_FOOTPRINTS.furnitureStone);
  if (fy == null || Math.abs(fy - y) > STONE_SEAT_PX) return null;
  return [Math.round(x), fy];
}

function main() {
  const check = process.argv.includes('--check');
  const source = JSON.parse(readFileSync(join(root, 'tools/snap-placements/stone-spots.json'), 'utf8'));
  const spots = {};
  const failed = [];
  for (const [tsid, row] of Object.entries(source.streets).sort(([a], [b]) => a.localeCompare(b))) {
    const street = JSON.parse(readFileSync(join(root, 'public/assets/streets', `${tsid}.json`), 'utf8'));
    const seated = seatStone(platformsScreen(street), row.spot);
    if (!seated) failed.push(`${row.label} (${tsid}) ${row.spot}`);
    else spots[tsid] = seated;
  }
  const text = `// Generated by tools/snap-placements/stone-spots.mjs from tools/snap-placements/stone-spots.json: never edit by hand.
/**
 * Visiting Stones where the Eleven players' 2012 snaps show them (G853, #392; the spawn audit matched our
 * own CC0 stone art, positions only): the stone's foot in street px (0, 0 = the street's top left),
 * seated on the floor under it. { [G tsid]: [x, y] }. street-furniture.js stoneSpotRow reads them.
 */
export const STONE_SPOTS = Object.freeze(${JSON.stringify(spots, null, 2).replace(/\[\n\s+(-?\d+(?:\.\d+)?),\n\s+(-?\d+(?:\.\d+)?)\n\s+\]/g, '[$1, $2]')});
`;
  const out = join(root, 'public/js/stone-spots-data.js');
  let before = '';
  try { before = readFileSync(out, 'utf8'); } catch { /* new */ }
  if (failed.length) console.error(`no floor under: ${failed.join('; ')}`);
  if (check) {
    if (before !== text || failed.length) {
      console.error('public/js/stone-spots-data.js is stale: run node tools/snap-placements/stone-spots.mjs');
      process.exit(1);
    }
    console.log(`stone spots are current (${Object.keys(spots).length} streets)`);
  } else {
    if (before !== text) writeFileSync(out, text);
    console.log(`${Object.keys(spots).length} stone spots -> public/js/stone-spots-data.js`);
    if (failed.length) process.exit(1);
  }
}

// Run only as a script: tests import the helpers above without writing anything.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
