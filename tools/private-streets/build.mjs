/**
 * G945 (audit M21, M22): the places Glitch kept to one player, from the location data.
 *
 * A location whose record names `instance_me` sent everyone who walked in to an instance of it
 * (main.js doors 1329-1353, players/player.js teleportToLocation 628-648), sharing one instance
 * only up to instances_get_max_members() players, which is 1 unless the record says more
 * (locations/inc_instances.js 88-90). So a location with instance_me and a max of 1 was a place
 * of your own: Gentle Island, the newxp exit streets, the colour levels and the like. Online
 * the remake keeps them private (Austin 2026-11-17): no presence of others, their quoins and
 * objects local (js/shared-street.js publicStreet).
 *
 * Two sources, one rule:
 *  - Tiny Speck's archived location XML (CC0): every L-prefixed record with
 *    `<str id="instance_me">` and `<int id="instance_max_members">` 1 or absent.
 *  - Rebuilt rooms whose XML is lost carry the same row on the room itself
 *    (`instance: { maxMembers, why }`, e.g. js/gwendolyn-room-23.js and
 *    js/tower-challenge-rooms.js); every room tools/build-tower-rooms.mjs writes is read.
 * Writes public/js/private-streets.js.
 *
 * Run from the game repo root:
 *   node tools/private-streets/build.mjs           writes the module
 *   node tools/private-streets/build.mjs --check   exits 1 when the module is stale
 * GRODDLE_LOCATION_XML overrides the location_data folder.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ALL_TOWER_ROOMS } from '../../public/js/tower-challenge-rooms.js?v=01f1c620';
import { MID_TOWER_ROOMS } from '../../public/js/tower-mid-rooms.js?v=2dd1122c';
import { GWENDOLYN_ROOMS } from '../../public/js/gwendolyn-room-23.js?v=918c0f6b';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
export const OUT_PATH = join(root, 'public/js/private-streets.js');
export const LOCATION_XML = process.env.GRODDLE_LOCATION_XML || join(root, '../streets/mnt/stos/location_data');

/** Rebuilt rooms (no archived XML), as tools/build-tower-rooms.mjs lists them. */
export const REBUILT_ROOMS = Object.freeze([...ALL_TOWER_ROOMS, ...MID_TOWER_ROOMS, ...GWENDOLYN_ROOMS]);

const unescape = (s) => String(s).replace(/&apos;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

/** One location record's instance row: { instanceMe, maxMembers } or null when it has none. */
export function instanceRow(xml) {
  const me = /<str id="instance_me">([^<]*)<\/str>/.exec(xml);
  if (!me || !me[1]) return null;
  const max = /<int id="instance_max_members">(-?\d+)<\/int>/.exec(xml);
  // inc_instances.js instances_get_max_members: `instance_max_members ? it : 1`.
  return { instanceMe: unescape(me[1]), maxMembers: max && Number(max[1]) ? Number(max[1]) : 1 };
}

/** The location's own label (its <game_object> line). */
function labelOf(xml) {
  const m = /<game_object [^>]*label="([^"]*)"/.exec(xml);
  return m ? unescape(m[1]) : '';
}

/** Every single-player place: [{ tsid (G-prefixed), label, instanceMe, from }] sorted by tsid. */
export function collectPrivateStreets({ xmlDir = LOCATION_XML, rooms = REBUILT_ROOMS } = {}) {
  const out = new Map();
  for (const file of readdirSync(xmlDir).filter((f) => /^L[A-Z0-9]+\.xml$/.test(f)).sort()) {
    const xml = readFileSync(join(xmlDir, file), 'utf8');
    const row = instanceRow(xml);
    if (!row || row.maxMembers !== 1) continue;
    const tsid = `G${file.slice(1, -4)}`;
    out.set(tsid, { tsid, label: labelOf(xml), instanceMe: row.instanceMe, from: `${file}` });
  }
  for (const room of rooms) {
    const inst = room?.instance;
    if (!inst || Number(inst.maxMembers) !== 1 || out.has(room.tsid)) continue;
    out.set(room.tsid, { tsid: room.tsid, label: room.label || '', instanceMe: inst.id || '', from: 'rebuilt room' });
  }
  return [...out.values()].sort((a, b) => a.tsid.localeCompare(b.tsid));
}

export function render(rows) {
  const xml = rows.filter((r) => r.from !== 'rebuilt room');
  const lines = rows.map((r) => `  '${r.tsid}', // ${r.label.replace(/\n/g, ' ')}${r.instanceMe ? ` (${r.instanceMe})` : ''}${r.from === 'rebuilt room' ? ', rebuilt room' : ''}`);
  return `/**
 * G945 (audit M21, M22): the places Glitch kept to one player: a location with instance_me and
 * a max of 1 member (locations/inc_instances.js 88-90) sent each player who entered to an
 * instance of their own. ${rows.length} places: ${xml.length} from Tiny Speck's archived location XML,
 * ${rows.length - xml.length} rebuilt rooms whose XML is lost (their \`instance\` row).
 * Online they stay private (js/shared-street.js publicStreet).
 * Generated by tools/private-streets/build.mjs; do not edit by hand.
 */

export const PRIVATE_STREETS = Object.freeze(new Set([
${lines.join('\n')}
]));

/** Whether Glitch kept this street (G- or L-prefixed tsid) to one player. */
export function isPrivateStreet(tsid) {
  const key = String(tsid || '');
  return PRIVATE_STREETS.has(key.startsWith('L') ? \`G\${key.slice(1)}\` : key);
}
`;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  if (!existsSync(LOCATION_XML)) {
    console.error(`private-streets: no location XML at ${LOCATION_XML} (set GRODDLE_LOCATION_XML)`);
    process.exit(1);
  }
  const text = render(collectPrivateStreets());
  const before = existsSync(OUT_PATH) ? readFileSync(OUT_PATH, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (before !== text) {
      console.error('public/js/private-streets.js is stale: run node tools/private-streets/build.mjs');
      process.exit(1);
    }
    console.log('private-streets: up to date');
  } else {
    if (before !== text) writeFileSync(OUT_PATH, text);
    console.log(`private-streets: ${before === text ? 'unchanged' : 'wrote public/js/private-streets.js'}`);
  }
}
