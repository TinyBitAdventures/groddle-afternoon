#!/usr/bin/env python3.11
"""The Ur subway's art (register row G115), rendered from Tiny Speck's own SWFs (CC0).

The 12 stations and the train car were never in the public locations dump, so the subway is laid out
from footage (js/subway.js) with the pieces of the one street bundle the client loaded for them,
tinyspeck/glitch-locations subway1.swf: the stone wall, the ceiling, columns, the track trench, the
train's nose, the ticket post and the gate block, each station's own name sign (sub_sign_*, the 2012
signs with the line dots and arrow that the footage shows), the stairs, cracks, the dripping pipe,
the car's interior wall with its benches, the windows and the six ads. Two items come from
tinyspeck/glitch-items: the Subway Map post (misc/subway_map) and A Red Button (misc/subway_gate).

Same pipeline as tools/room-art/build.py (which only reads street bundles): FFDec renders each SWF
once (tools/deco-pipeline render_batch), its stage is resampled (Lanczos) to the output size and
encoded as WebP. `scale` is world px per SWF stage px, read off the footage against the avatar
(about 1.45 world px per video px in Lily Linguistic's clips VVyjuuRxDUw and bvOH7rsQ6qo, where the
ads, windows and benches come out at their stage size); `density` is texels per world px.

Writes public/assets/sprites/subway/*.webp, tools/subway-art.json (plan) and public/js/subway-art.js
(name -> [file, world w, world h]).

Usage (python3.11 has numpy + Pillow; FFDec needs Java 21; cwebp):
  python3.11 -I tools/build-subway-art.py --work <scratch dir> [--force]
  python3.11 -I tools/build-subway-art.py --check     (no rendering; exit 1 on a problem)
The SWFs are data: FFDec reads them, nothing runs them.
"""
import argparse, json, math, os, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPIKE = os.path.dirname(HERE)
sys.dont_write_bytecode = True
for sub in ('deco-audit', 'icon-hires', 'deco-pipeline'):
    sys.path.insert(0, os.path.join(SPIKE, 'tools', sub))
import audit  # noqa: E402
import swfinfo  # noqa: E402
import build as deco  # noqa: E402  (tools/deco-pipeline/build.py)

PUBLIC = os.path.join(SPIKE, 'public')
OUT = os.path.join(PUBLIC, 'assets', 'sprites', 'subway')
PLAN = os.path.join(HERE, 'subway-art.json')
OUT_JS = os.path.join(PUBLIC, 'js', 'subway-art.js')
ITEMS = os.path.join(os.path.dirname(SPIKE), 'glitch-items')
BUNDLE = 'subway1.swf'

STATION_SIGNS = ['eastern_approach', 'gregarious_grange', 'groddle_forest_junction', 'jutuan_central', 'kongu_hop',
                 'mallos_means', 'onto_parada', 'pitika_parse', 'somewhat_sump', 'tallish_crest', 'thiruvan_thrive',
                 'torpan_cleft']

# name -> (scale, density, source). source 'bundle' is subway1.swf; otherwise a glitch-items path.
PIECES = {
    # The station (footage t0000-t0012 of both clips): wall tiles, ceiling, trench, column, train nose.
    'wall_1': (1, 1.5, 'bundle'),
    'ceiling_1': (1, 1.5, 'bundle'),
    'back_platform_1': (1, 1.5, 'bundle'),
    'column_1': (1, 2, 'bundle'),
    'train_1': (1.15, 2, 'bundle'),
    'ticket_post_back': (1, 2, 'bundle'),
    'subway_gate_static': (1, 2, 'bundle'),
    'door_asset_stairs': (1, 2, 'bundle'),
    'wall_crack_1': (1, 2, 'bundle'),
    'wall_crack_2': (1, 2, 'bundle'),
    'wallpipe_1': (1, 2, 'bundle'),
    'platform_crack_1': (1, 2, 'bundle'),
    'light_1': (1, 2, 'bundle'),
    **{f'sub_sign_{s}': (0.8, 2.5, 'bundle') for s in STATION_SIGNS},
    # The car: the interior wall (ceiling band, riveted wall, three benches, floor), windows, ads.
    'subway_interior_1': (1, 1.5, 'bundle'),
    'subway_window_static': (1, 2, 'bundle'),
    'subway_interior_pole_1': (1, 2, 'bundle'),
    'subway_interior_floor_light': (1, 2, 'bundle'),
    **{f'subway_ad_{i}': (1, 2, 'bundle') for i in range(1, 7)},
    # The Subway System map's markers.
    'subway_map_current_station_red': (1, 2, 'bundle'),
    'subway_map_current_station_blue': (1, 2, 'bundle'),
    'subway_map_next_stop_red': (1, 2, 'bundle'),
    'subway_map_next_stop_blue': (1, 2, 'bundle'),
    # Items (glitch-items, CC0): the Subway Map post and A Red Button, at their stage size.
    'subway_map': (1, 2, 'misc/subway_map/subway_map.swf'),
    'subway_gate': (1, 3, 'misc/subway_gate/subway_gate.swf'),
}


def file_name(name, density):
    return f'{name}@{density:g}x.webp'


def source_label(src, name):
    return f'bundle:{BUNDLE}#{name}' if src == 'bundle' else f'glitch-items:{src}'


def swf_path(work, src, name, index):
    if src == 'bundle':
        return audit.bundled_swf(work, BUNDLE, name, index)
    return os.path.join(ITEMS, src)


def write_js(rows):
    lines = ['// Generated by tools/build-subway-art.py from tinyspeck/glitch-locations subway1.swf and',
             '// tinyspeck/glitch-items misc/subway_map, misc/subway_gate (CC0). Do not edit.',
             '// name -> [file in assets/sprites/subway/, world w, world h].',
             'export const SUBWAY_ART = Object.freeze({']
    for name, r in sorted(rows.items()):
        lines.append(f"  {name}: ['{r['file']}', {r['world'][0]}, {r['world'][1]}],")
    lines.append('});')
    return '\n'.join(lines) + '\n'


def cmd_build(args):
    index = audit.bundle_index()
    os.makedirs(args.work, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    plan = json.load(open(PLAN)) if os.path.exists(PLAN) else {}
    rows = plan.get('pieces', {})
    todo = []
    for name, (scale, density, src) in PIECES.items():
        swf = swf_path(args.work, src, name, index)
        swf_sha = deco.sha(swf)[:16]
        stage = swfinfo.read(swf)['stage']
        px = [max(1, round(stage[0] * scale * density)), max(1, round(stage[1] * scale * density))]
        row = {'scale': scale, 'density': density, 'stage': stage, 'px': px, 'file': file_name(name, density),
               'swf': source_label(src, name), 'swf_sha': swf_sha,
               'key': f'{swf_sha}:{scale}:{density}:{json.dumps(deco.SETTINGS, sort_keys=True)}'}
        old = rows.get(name) or {}
        if not args.force and old.get('key') == row['key'] and os.path.exists(os.path.join(OUT, row['file'])):
            continue
        row['_swf'] = swf
        row['zoom'] = max(1, math.ceil(scale * density - 0.02))
        todo.append((name, row))
    print(f'subway: {len(PIECES)} pieces; to do: {len(todo)}', flush=True)
    by_zoom = {}
    for name, row in todo:
        by_zoom.setdefault(row['zoom'], []).append((name, row))
    for zoom, batch in sorted(by_zoom.items()):
        found, tmp = deco.render_batch(args.work, zoom, [(n, r['_swf']) for n, r in batch])
        for name, row in batch:
            if name not in found:
                raise SystemExit(f'{name}: FFDec produced no frame')
            img = deco.stage_resample(deco.load(found[name]), row['stage'], zoom, row['px'])
            row['out_px'] = list(img.size)
            row['world'] = [math.floor(img.size[0] / row['density'] + 0.5), math.floor(img.size[1] / row['density'] + 0.5)]
            dst = os.path.join(OUT, row['file'])
            row['bytes'], row['lossless'], row['err'] = deco.encode(img, dst, os.path.join(args.work, 'enc'))
            row['sha'] = deco.sha(dst)[:16]
            for k in ('_swf', 'zoom'):
                row.pop(k, None)
            rows[name] = row
            print(f'  {row["file"]} {row["out_px"][0]}x{row["out_px"][1]} {row["bytes"]} B', flush=True)
        for p in tmp:
            shutil.rmtree(p, ignore_errors=True)
    for name in list(rows):
        if name not in PIECES:
            old = os.path.join(OUT, rows[name]['file'])
            if os.path.exists(old):
                os.remove(old)
            del rows[name]
    plan = {'source': 'tinyspeck/glitch-locations subway1.swf, tinyspeck/glitch-items (CC0), rendered by tools/deco-pipeline',
            'settings': deco.SETTINGS, 'tools': deco.tool_versions(), 'pieces': dict(sorted(rows.items()))}
    with open(PLAN, 'w') as f:
        json.dump(plan, f, indent=1)
        f.write('\n')
    with open(OUT_JS, 'w') as f:
        f.write(write_js(rows))
    print('total bytes', sum(r['bytes'] for r in rows.values()))


def cmd_check():
    bad = 0
    if not os.path.exists(PLAN):
        print('no plan')
        return 1
    rows = json.load(open(PLAN))['pieces']
    for name, (scale, density, src) in PIECES.items():
        row = rows.get(name)
        if not row or row['scale'] != scale or row['density'] != density or row['swf'] != source_label(src, name):
            print(f'{name}: not built as {(scale, density, src)}'); bad += 1; continue
        path = os.path.join(OUT, row['file'])
        if not os.path.exists(path) or deco.sha(path)[:16] != row['sha']:
            print(f'{name}: {row["file"]} missing or changed'); bad += 1
    for name in rows:
        if name not in PIECES:
            print(f'{name}: in the plan but not a piece'); bad += 1
    if not os.path.exists(OUT_JS) or open(OUT_JS).read() != write_js(rows):
        print('public/js/subway-art.js is stale'); bad += 1
    print('ok' if not bad else f'{bad} problems')
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--work', help='scratch dir for renders')
    ap.add_argument('--force', action='store_true')
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    if args.check:
        sys.exit(cmd_check())
    if not args.work:
        ap.error('--work is required to build')
    cmd_build(args)


if __name__ == '__main__':
    main()
