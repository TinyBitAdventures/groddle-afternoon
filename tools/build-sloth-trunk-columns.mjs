#!/usr/bin/env node
/**
 * #746 (R2): the drawn trunk of every tree a Sloth can hang in, row by row, so js/sloth-trees.js puts
 * the Knocker on the trunk as drawn and the sloth's own branch up to it, not on the trunk deco's box:
 * the trunk art is lopsided (tree_plane_trunk_01a's trunk stands about 40 px right of its box's
 * middle). For each `tree_plane_trunk_*` / `tree_plane_01a` sprite in the deco manifest, the art
 * street-render.js draws (public/assets/decos/groddle/<sprite>.webp) is measured with ImageMagick:
 * one row per ROW_CELL px of the art, its leftmost and rightmost columns where the alpha is over
 * half. Writes public/js/sloth-trunk-columns-data.js.
 *
 *   node tools/build-sloth-trunk-columns.mjs           measure (needs ImageMagick) and write
 *   node tools/build-sloth-trunk-columns.mjs --check   exit 1 when the file is stale or a sloth street's trunk has no columns
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = 'public/js/sloth-trunk-columns-data.js';
/** The art's px a row covers. */
export const ROW_CELL = 4;
/** The trunk sprites (js/sloth-trees.js TRUNK_RE). */
const TRUNK_RE = /^tree_plane_trunk|^tree_plane_01a/;
const read = (rel) => JSON.parse(readFileSync(join(root, rel), 'utf8'));

/** The trunk sprites the manifest has, sorted. */
export function trunkSprites() {
  return read('public/assets/decos/manifest.json').filter((name) => TRUNK_RE.test(name)).sort();
}

/** The trunk sprites the sloth streets' own art uses (assets/content/street-ecology.json counts.npc_sloth). */
function slothStreetSprites() {
  const ecology = read('public/assets/content/street-ecology.json');
  const names = new Set();
  for (const [tsid, row] of Object.entries(ecology.streets || {})) {
    if (!(Number(row?.counts?.npc_sloth) > 0)) continue;
    for (const layer of read(`public/assets/streets/${tsid}.json`).layers || []) {
      for (const d of layer.decos || []) if (TRUNK_RE.test(String(d.sprite || ''))) names.add(d.sprite);
    }
  }
  return [...names].sort();
}

function measure(names) {
  const out = {};
  for (const name of names) {
    const file = join(root, 'public/assets/decos/groddle', `${name}.webp`);
    const [w, ih] = execFileSync('magick', ['identify', '-format', '%w %h', file], { encoding: 'utf8' }).trim().split(' ').map(Number);
    const h = Math.max(1, Math.ceil(ih / ROW_CELL));
    const raw = execFileSync('magick', [file, '-alpha', 'extract', '-filter', 'box', '-resize', `${w}x${h}!`, '-depth', '8', 'gray:-'], { maxBuffer: 1 << 26 });
    const rows = [];
    for (let y = 0; y < h; y += 1) {
      let l = -1;
      let r = -1;
      for (let x = 0; x < w; x += 1) {
        if (raw[y * w + x] < 128) continue;
        if (l < 0) l = x;
        r = x + 1;
      }
      rows.push(l, r);
    }
    out[name] = { w, h, rows };
  }
  return out;
}

function render(columns) {
  const rows = Object.entries(columns).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  return `// Generated by tools/build-sloth-trunk-columns.mjs: never edit by hand.
/**
 * #746: where each trunk sprite's art is drawn, for js/sloth-trees.js (the Knocker on the drawn trunk,
 * the sloth's branch up to it). { [sprite]: { w, h, rows } }: the art is w columns wide, cut in h
 * rows top to bottom; rows holds each row's [left, right) columns where the alpha is over half, flat
 * (-1, -1 = nothing drawn).
 */
export const SLOTH_TRUNK_COLUMNS = Object.freeze({
${rows.join('\n')}
});
`;
}

function main() {
  const names = trunkSprites();
  const text = render(measure(names));
  const missing = slothStreetSprites().filter((n) => !names.includes(n));
  if (missing.length) {
    console.error(`sloth street trunks with no art to measure: ${missing.join(', ')}`);
    process.exit(1);
  }
  if (process.argv.includes('--check')) {
    let before = '';
    try { before = readFileSync(join(root, OUT), 'utf8'); } catch { /* new */ }
    if (before !== text) {
      console.error(`${OUT} is stale: run node tools/build-sloth-trunk-columns.mjs`);
      process.exit(1);
    }
    console.log(`${OUT} is current (${names.length} trunks)`);
    return;
  }
  writeFileSync(join(root, OUT), text);
  console.log(`wrote ${OUT} (${names.length} trunks: ${names.join(' ')})`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
