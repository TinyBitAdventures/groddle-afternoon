#!/usr/bin/env python3.11
"""Locked doors show the keyhole of the key that opens them (player report 34, 2026-11-01).

Tiny Speck's lock door decos (door_asset_apartment_door_lock, door_asset_heights_door_lock, the
wooden and Jethimadh ones) carry all twelve keyholes on their stage, `keyhole1`..`keyhole12`, one
over the other. The client showed one: DoorView.as 243-244 calls the deco's showLock(key_id) for a
locked door, and the deco's own frame script (door_asset_apartment_door_lock.fla, DOMDocument.xml)
hides every keyhole and then shows `'keyhole' + key_id`, the shape and colours of
items/door_key_<key_id>.js (keyhole 5 is the Red-Green Triangle Key's triangle). A static render
of the SWF (tools/deco-pipeline/build.py) shows all twelve stacked, so every lock in the game read
as the same rainbow hexagon whatever key it needed.

This tool renders, for every (lock deco, key_id) a street places (street JSON `doors`, key_id > 0),
the deco SWF with only that keyhole left on the stage: FFDec -swf2xml, drop the other `keyhole<N>`
PlaceObject tags, -xml2swf, then the same render and resampling as build.py, written as
public/assets/decos/door-locks/<deco>__key<N>@1.5x.webp (the 3x art: a door is drawn at its own
rect, so one file serves every screen). js/door-lock-art.js lists them; features/doors-feature.js
draws a locked door from its key's file and falls back to the plain deco.
Decos with no SWF in the plan, or whose SWF has no keyholes, are listed as skipped.

Usage (python3.11 has numpy + Pillow; FFDec needs Java 21; cwebp 1.6):
  python3.11 -I tools/deco-pipeline/door-locks.py --work <scratch dir> [--force]
  python3.11 -I tools/deco-pipeline/door-locks.py --check     (no rendering; exit 1 on any problem)
"""
import argparse, json, os, re, shutil, sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
sys.dont_write_bytecode = True  # no __pycache__ in tools/
sys.path.insert(0, HERE)
import build  # noqa: E402  (paths, FFDec, stage_resample, encode)
audit = build.audit

OUT = os.path.join(build.PUBLIC, 'assets', 'decos', 'door-locks')
STREETS = build.STREETS
PLAN = os.path.join(HERE, 'door-locks.json')
JS = os.path.join(build.PUBLIC, 'js', 'door-lock-art.js')
KEYHOLE = re.compile(r'keyhole(\d+)')
VERSION = 1


def placed_pairs():
    """{deco: sorted key ids} for every keyed door on a street."""
    out = {}
    for f in sorted(os.listdir(STREETS)):
        if not f.endswith('.json') or f == 'index.json':
            continue
        try:
            street = json.load(open(os.path.join(STREETS, f)))
        except Exception:
            continue
        for d in street.get('doors') or []:
            k = int(d.get('key_id') or 0)
            if k > 0 and d.get('sprite'):
                out.setdefault(d['sprite'], set()).add(k)
    return {s: sorted(v) for s, v in sorted(out.items())}


def file_name(deco, key):
    return f'{deco}__key{key}@1.5x.webp'


def keep_keyhole(src_xml, dst_xml, key):
    """Write the SWF XML with every keyhole<N> placement but `key`'s removed; returns names found."""
    tree = ET.parse(src_xml)
    found = set()
    for parent in tree.iter():
        for ch in list(parent):
            m = KEYHOLE.fullmatch(ch.get('name') or '')
            if not m or not ch.get('type', '').startswith('PlaceObject'):
                continue
            found.add(int(m.group(1)))
            if int(m.group(1)) != key:
                parent.remove(ch)
    tree.write(dst_xml, encoding='utf-8', xml_declaration=True)
    return found


def out_size(row):
    if row.get('size3'):
        return list(row['size3'])
    return [round(v * 1.5) for v in row['size2']]


def js_text(plan):
    art = {d: sorted(int(k) for k in rows) for d, rows in plan['decos'].items() if rows}
    lines = [
        '/**',
        ' * Generated by tools/deco-pipeline/door-locks.py: the lock decos rendered with only one',
        " * keyhole showing (the deco's showLock(key_id), DoorView.as 243-244). Do not edit.",
        ' */',
        f'export const DOOR_LOCK_ART = Object.freeze({json.dumps(art, separators=(",", ":"))});',
        '',
        '/** The file for a locked door of `deco` that `keyId` opens, or null (draw the plain deco). */',
        'export function doorLockArt(deco, keyId) {',
        '  const k = Number(keyId);',
        '  return DOOR_LOCK_ART[deco]?.includes(k) ? `assets/decos/door-locks/${deco}__key${k}@1.5x.webp` : null;',
        '}',
        '',
    ]
    return '\n'.join(lines)


def read_plan():
    if os.path.exists(PLAN):
        return json.load(open(PLAN))
    return {'version': VERSION, 'decos': {}, 'skipped': {}}


def write_plan(plan):
    with open(PLAN, 'w') as f:
        json.dump(plan, f, indent=1, sort_keys=True)
        f.write('\n')
    with open(JS, 'w') as f:
        f.write(js_text(plan))


def cmd_build(args):
    work = os.path.abspath(args.work)
    os.makedirs(work, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    deco_plan = build.read_plan()['decos']
    plan = read_plan()
    plan['version'] = VERSION
    done, skipped = {}, {}
    for deco, keys in placed_pairs().items():
        row = deco_plan.get(deco)
        label = (row or {}).get('swf')
        if not row or not label or row.get('mode') != 'swf':
            skipped[deco] = 'no SWF render in plan.json (deco kept as its PNG)'
            continue
        swf = audit.swf_path(label, work)
        swf_sha = build.sha(swf)[:16]
        prev = plan['decos'].get(deco) or {}
        size = out_size(row)
        todo = [k for k in keys if args.force or (prev.get(str(k)) or {}).get('swf_sha') != swf_sha
                or (prev.get(str(k)) or {}).get('size') != size
                or not os.path.exists(os.path.join(OUT, file_name(deco, k)))]
        rows = {str(k): prev[str(k)] for k in keys if str(k) in prev and k not in todo}
        if todo:
            d = os.path.join(work, 'door-locks', deco)
            shutil.rmtree(d, ignore_errors=True)
            os.makedirs(d)
            full = os.path.join(d, 'full.xml')
            build.ffdec('-swf2xml', swf, full)
            items = []
            for k in todo:
                x = os.path.join(d, f'k{k}.xml')
                found = keep_keyhole(full, x, k)
                if k not in found:
                    skipped[f'{deco}#{k}'] = f'no keyhole{k} on the stage (has {sorted(found)})'
                    continue
                s = os.path.join(d, f'{deco}__key{k}.swf')
                build.ffdec('-xml2swf', x, s)
                os.remove(x)  # each XML is the whole deco: keep the work dir small
                if os.path.exists(s):
                    items.append((f'{deco}__key{k}', s))
            renders, _src, _out = audit.export_frames(d, 'r', items, row.get('zoom') or build.SETTINGS['zoom'])
            for key_name, _ in items:
                k = int(key_name.rsplit('__key', 1)[1])
                if key_name not in renders:
                    skipped[f'{deco}#{k}'] = 'FFDec render failed'
                    continue
                img = build.stage_resample(build.load(renders[key_name]), row['stage'], row.get('zoom') or build.SETTINGS['zoom'], size)
                dst = os.path.join(OUT, file_name(deco, k))
                nbytes, lossless, err = build.encode(img, dst, os.path.join(d, 'enc'))
                rows[str(k)] = {'swf_sha': swf_sha, 'size': size, 'bytes': nbytes, 'lossless': lossless,
                                'err': err, 'sha': build.sha(dst)[:16]}
                print(f'{deco} key {k}: {nbytes} bytes')
            shutil.rmtree(d, ignore_errors=True)
        if rows:
            done[deco] = dict(sorted(rows.items(), key=lambda kv: int(kv[0])))
    # Files for pairs no street places any more go.
    for deco, rows in plan['decos'].items():
        for k in rows:
            if k not in (done.get(deco) or {}):
                p = os.path.join(OUT, file_name(deco, int(k)))
                if os.path.exists(p):
                    os.remove(p)
    plan['decos'] = done
    plan['skipped'] = dict(sorted(skipped.items()))
    write_plan(plan)
    print(f"{sum(len(r) for r in done.values())} lock files, {len(skipped)} skipped")
    return 0


def cmd_check(_args):
    plan = read_plan()
    bad = []
    pairs = placed_pairs()
    for deco, keys in pairs.items():
        for k in keys:
            if str(k) not in (plan['decos'].get(deco) or {}) and deco not in plan['skipped'] and f'{deco}#{k}' not in plan['skipped']:
                bad.append(f'{deco} key {k}: placed but not built (run --work)')
    for deco, rows in plan['decos'].items():
        for k, r in rows.items():
            if int(k) not in pairs.get(deco, []):
                bad.append(f'{deco} key {k}: built but no street places it')
            p = os.path.join(OUT, file_name(deco, int(k)))
            if not os.path.exists(p):
                bad.append(f'{p}: missing')
            elif build.sha(p)[:16] != r['sha']:
                bad.append(f'{p}: changed since the build')
    if not os.path.exists(JS) or open(JS).read() != js_text(plan):
        bad.append(f'{JS}: stale (run --work)')
    for b in bad:
        print(b)
    print('door-locks check:', 'ok' if not bad else f'{len(bad)} problem(s)')
    return 1 if bad else 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--work')
    ap.add_argument('--force', action='store_true')
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    if a.check:
        return cmd_check(a)
    if not a.work:
        ap.error('--work <scratch dir> or --check')
    return cmd_build(a)


if __name__ == '__main__':
    sys.exit(main())
