/**
 * G152 bags: the item facts the pack's slots need, from Tiny Speck's
 * GameServerJS items (CC0), read as text, nothing evaluated.
 *
 *  - stackmax: `var stackmax = N` in items/<class>.js. A pack or bag slot holds
 *    one stack of at most this many (items/bag.js:82-88, 191-206).
 *  - What the special bags take (their canContain): spices `this.is_spice = 1`
 *    (bag_spicerack.js:588-591), compounds `this.is_compound = 1`
 *    (bag_alchemistry_kit.js:588-591), elements `this.is_element = 1`
 *    (bag_elemental_pouch.js:651-659), cubimals with npc_cubimal_base in
 *    parent_classes (bag_cubimal_case.js:588-591), tools by the `tool` tag
 *    (bag_toolbox_base canContain, bag_toolbox_red.js:588-590).
 *  - What no ordinary bag takes: `no_bag` tag, bags (`bag` tag or a bag_ id)
 *    and furniture (bag_generic.js:588-590).
 *  - What takes no pack slot at all: furniture (furniture_base parent) and
 *    trophies (`var is_trophy = true`), which the source kept in hidden bags
 *    (items/bag.js:98-104).
 *
 * Run from the game repo root:
 *   node tools/build-pack-slots.mjs           writes public/js/pack-slots-data.js
 *   node tools/build-pack-slots.mjs --check   exits 1 when it is stale
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readItemTags, readItems } from './inventory/gsjs-data.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const GSJS = join(root, '..', 'glitch-GameServerJS');
export const OUT = join(root, 'public/js/pack-slots-data.js');

const flag = (text, name) => new RegExp(`^\\s*this\\.${name}\\s*=\\s*(1|true)\\s*;`, 'm').test(text);

/** The generated module text for one GameServerJS checkout. */
export function packSlotsSource(gsjs = GSJS) {
  const items = readItems(gsjs, readItemTags(gsjs));
  const stackmax = {};
  const sets = { spice: [], compound: [], element: [], cubimal: [], tool: [], noBag: [], noSlot: [] };
  for (const it of items) {
    const text = readFileSync(join(gsjs, 'items', `${it.id}.js`), 'utf8');
    const m = /^var stackmax\s*=\s*(\d+)\s*;/m.exec(text);
    if (!it.takeable) continue;
    const max = m ? Math.max(1, Number(m[1])) : 1;
    stackmax[it.id] = max;
    const parents = it.parents || [];
    if (flag(text, 'is_spice')) sets.spice.push(it.id);
    if (flag(text, 'is_compound')) sets.compound.push(it.id);
    if (flag(text, 'is_element')) sets.element.push(it.id);
    if (parents.includes('npc_cubimal_base')) sets.cubimal.push(it.id);
    if (it.tags.includes('tool')) sets.tool.push(it.id);
    if (it.tags.includes('no_bag')) sets.noBag.push(it.id);
    const trophy = /^var is_trophy\s*=\s*true/m.test(text) || flag(text, 'is_trophy');
    if (trophy || parents.includes('furniture_base')) sets.noSlot.push(it.id);
  }
  // Group the stackmax table by value so the module stays small.
  const byMax = {};
  for (const [id, max] of Object.entries(stackmax)) (byMax[max] ||= []).push(id);
  const groups = Object.keys(byMax)
    .map(Number)
    .sort((a, b) => a - b)
    .map((max) => `  ${max}: ${JSON.stringify(byMax[max].sort().join(' '))},`)
    .join('\n');
  const lines = [
    '/* Generated by tools/build-pack-slots.mjs from glitch-GameServerJS items (CC0). Do not edit. */',
    '',
    '/** Takeable classes by stackmax (items/<class>.js var stackmax); one pack slot holds one stack. */',
    'const STACKMAX_GROUPS = {',
    groups,
    '};',
    '',
    '/** @type {Map<string, number>} */',
    'export const STACKMAX = new Map();',
    'for (const [max, ids] of Object.entries(STACKMAX_GROUPS)) for (const id of ids.split(\' \')) STACKMAX.set(id, Number(max));',
    '',
    `export const SPICE_CLASSES = new Set(${JSON.stringify(sets.spice.sort())});`,
    `export const COMPOUND_CLASSES = new Set(${JSON.stringify(sets.compound.sort())});`,
    `export const ELEMENT_CLASSES = new Set(${JSON.stringify(sets.element.sort())});`,
    `export const CUBIMAL_CLASSES = new Set(${JSON.stringify(sets.cubimal.sort())});`,
    `export const TOOL_CLASSES = new Set(${JSON.stringify(sets.tool.sort())});`,
    `export const NO_BAG_CLASSES = new Set(${JSON.stringify(sets.noBag.sort())});`,
    '/** Furniture and trophies: the source kept them in hidden bags, never in pack slots (items/bag.js:98-104). */',
    `export const NO_SLOT_CLASSES = new Set(${JSON.stringify(sets.noSlot.sort())});`,
    '',
  ];
  return lines.join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!existsSync(join(GSJS, 'items'))) {
    console.error(`No GameServerJS at ${GSJS}`);
    process.exit(2);
  }
  const next = packSlotsSource();
  const check = process.argv.includes('--check');
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (check) {
    if (now !== next) {
      console.error('public/js/pack-slots-data.js is stale: run node tools/build-pack-slots.mjs');
      process.exit(1);
    }
    console.log('pack-slots-data.js is current');
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT} (${next.length} bytes)`);
  }
}
