/**
 * The Auction House between real players (register G333): which classes may
 * be listed and the category each is browsed under, for the site
 * (groddle-afternoon-site data/auctions.json, read by src/LedgerAuction.php).
 * The game reads the categories from the site's answers, so this is the one
 * copy.
 *
 * Source rules (glitch-GameServerJS, read as text, nothing evaluated):
 *  - Only what the ledger carries can be listed: the tradeable classes of
 *    public/assets/content/trade-items.json (tools/build-realtime-trade.mjs,
 *    the same set as the site's data/economy.json), so soulbound and no_trade
 *    items are already out (inc_auctions.js:107-112 stack_is_soulbound).
 *  - players/inc_auctions.js admin_auctions_start (764-820, 789) refuses a stack
 *    tagged no_auction or bag (not_allowed), with
 *    the tags of items/<id>.js `var tags` plus items/catalog_tags.js.
 *  - Categories: glitch.com's auction pages browsed by item tag. The keys and
 *    names are the 2012 site's Glitch.Auctions.category_map (Wayback
 *    www.glitch.com/auctions/page2/ 20120801095711, saved under
 *    research/wayback/raw/auctions/pages/), in its order; a class goes under
 *    the first key it carries as a tag, furniture under Furniture (the 2012
 *    site's /auctions/cat-furniture/, whose sub-categories cannot be read
 *    from the item files), anything else under Other.
 *
 * Run from the game repo root:
 *   node tools/build-auctions.mjs           writes the site repo's data/auctions.json
 *   node tools/build-auctions.mjs --check   exits 1 when it is stale
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireSite, sitePath } from './repos.mjs';
import { readItemTags, readItems } from './inventory/gsjs-data.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const GSJS = join(root, '..', 'glitch-GameServerJS');
export const TRADE = join(root, 'public/assets/content/trade-items.json');
export const OUT = sitePath('data', 'auctions.json');

/** Glitch.Auctions.category_map (2012), in its order; Furniture and Other last. */
export const CATEGORIES = Object.freeze([
  ['advanced_resource', 'Advanced Resources'],
  ['alchemy', 'Alchemical Compounds & Powders'],
  ['basic_resource', 'Basic Resources'],
  ['collectible', 'Collectibles'],
  ['croppery_gardening_supplies', 'Croppery & Gardening Supplies'],
  ['drink', 'Drink'],
  ['emblems_icons', 'Emblems & Icons'],
  ['food', 'Food'],
  ['gassesbubbles', 'Gasses & Bubbles'],
  ['herbalism_supplies', 'Herbalism Supplies'],
  ['herdkeepingsupplies', 'Herdkeeping Supplies'],
  ['key', 'Keys'],
  ['bureaucracy', 'Licenses & Permits'],
  ['machineparts_products', 'Machines & Fuel'],
  ['spice', 'Spices'],
  ['tinctures_potions', 'Tinctures & Potions'],
  ['tool', 'Tools'],
  ['toys', 'Toys'],
  ['upgrade_card', 'Upgrade Cards'],
  ['furniture', 'Furniture'],
  ['other', 'Other'],
]);

/** admin_auctions_start (inc_auctions.js:789): not_allowed. */
export const REFUSED_TAGS = Object.freeze(['no_auction', 'bag']);

export function auctionTable(gsjs = GSJS) {
  const trade = JSON.parse(readFileSync(TRADE, 'utf8'));
  const tags = new Map(readItems(gsjs, readItemTags(gsjs)).map((it) => [it.id, new Set(it.tags)]));
  const keys = CATEGORIES.map(([k]) => k);
  const items = {};
  const refused = {};
  for (const c of Object.keys(trade.items).sort()) {
    const t = tags.get(c) || new Set();
    const why = REFUSED_TAGS.find((x) => t.has(x));
    if (why) {
      refused[c] = why;
      continue;
    }
    const cat = keys.find((k) => k !== 'other' && t.has(k)) || 'other';
    items[c] = cat;
  }
  return {
    _doc: 'Generated by the game repo\'s tools/build-auctions.mjs from glitch-GameServerJS item tags and the trade table (do not edit). cats: [key, name] in the 2012 auction pages\' order; items: listable class -> category key; refused: tradeable classes the source would not auction, and the tag why (inc_auctions.js admin_auctions_start). G333.',
    cats: CATEGORIES,
    items,
    refused,
  };
}

export function auctionJson(gsjs = GSJS) {
  const t = auctionTable(gsjs);
  const map = (o) => Object.entries(o).map(([k, v]) => `${JSON.stringify(k)}:${JSON.stringify(v)}`).join(',\n');
  return `{"_doc":${JSON.stringify(t._doc)},\n"cats":${JSON.stringify(t.cats)},\n"items":{\n${map(t.items)}},\n"refused":{\n${map(t.refused)}}}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  requireSite();
  const text = auctionJson();
  if (process.argv.includes('--check')) {
    let have = '';
    try { have = readFileSync(OUT, 'utf8'); } catch { /* missing */ }
    if (have !== text) {
      console.error(`${OUT} is stale: run node tools/build-auctions.mjs`);
      process.exit(1);
    }
    process.exit(0);
  }
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
  const t = auctionTable();
  const per = {};
  for (const k of Object.values(t.items)) per[k] = (per[k] || 0) + 1;
  console.log(`auction table: ${Object.keys(t.items).length} listable, ${Object.keys(t.refused).length} refused; ${JSON.stringify(per)}`);
}
