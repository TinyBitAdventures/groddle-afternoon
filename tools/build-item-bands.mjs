#!/usr/bin/env node
/**
 * Build public/js/item-bands-data.js: which of the client's three item holders
 * each item class draws in, from Tiny Speck's GameServerJS and glitch-client (CC0).
 *
 *   node tools/build-item-bands.mjs [path/to/glitch-GameServerJS] [--check]
 *
 * The client stacks the middleground back to front (MiddleGroundRenderer.setupEndShapes
 * 111-171): decos, BG_ITEM, NRM_ITEM, FG_ITEM, other avatars, your avatar, FOREMOST_ITEMS,
 * FG_FURN. LocationRenderer.placeItemstackInMG 1508-1517 picks the holder from the class's
 * itemDef flags: in_background first, then in_foreground, then in_foremostground, else normal.
 * The flags come from each items/<class>.js `var itemDef = { in_background, in_foreground }`;
 * in_foremostground is set only by the client (Item.fromAnonymous 436-440, the Crusher).
 * Within a holder each stack goes in under the holder's marker in stack-z order
 * (WorldModel.getItemstacksASortedByZ, LayerRenderer.addUnder), so a later stack is on top.
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const GSJS = process.argv.slice(2).find((a) => !a.startsWith('--')) || join(ROOT, '..', 'glitch-GameServerJS');
const CLIENT = join(ROOT, '..', 'glitch-client', 'com/tinyspeck/engine');
const OUT = join(ROOT, 'public/js/item-bands-data.js');

/** Used when glitch-client is not beside the repo (Item.as 436-440). */
const FOREMOST_FALLBACK = ['crusher'];

function fail(msg) {
  throw new Error(`build-item-bands: ${msg}`);
}

/** The classes Item.fromAnonymous forces into FOREMOST_ITEMS. */
function foremostClasses() {
  const file = join(CLIENT, 'data/item/Item.as');
  if (!existsSync(file)) return FOREMOST_FALLBACK;
  const src = readFileSync(file, 'utf8');
  const out = [...src.matchAll(/if \(item\.tsid == '([a-z0-9_]+)'\) \{\s*item\.in_foremostground = true;/g)].map((m) => m[1]);
  if (!out.length) fail('Item.as: no in_foremostground class');
  return out.sort();
}

export function buildItemBands(gsjs = GSJS) {
  const dir = join(gsjs, 'items');
  if (!existsSync(dir)) fail(`no ${dir}`);
  const background = [];
  const foreground = [];
  const normal = [];
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.js')).sort()) {
    const src = readFileSync(join(dir, file), 'utf8');
    const at = src.indexOf('var itemDef = {');
    if (at < 0) continue; // catalogs and includes, not item classes
    const body = src.slice(at, src.indexOf('};', at));
    const flag = (name) => {
      const m = new RegExp(`\\n\\s*${name}\\s*:\\s*(true|false)\\s*,`).exec(body);
      if (!m) fail(`${file}: no ${name} in itemDef`);
      return m[1] === 'true';
    };
    const cls = file.slice(0, -3);
    // LocationRenderer.placeItemstackInMG: in_background wins over in_foreground.
    if (flag('in_background')) background.push(cls);
    else if (flag('in_foreground')) foreground.push(cls);
    else normal.push(cls);
  }
  const foremost = foremostClasses();
  const pull = (list) => list.filter((c) => !foremost.includes(c));
  return { background: pull(background), normal: pull(normal), foreground: pull(foreground), foremost };
}

function list(name, classes, note) {
  const lines = [`// ${note} (${classes.length})`, `export const ${name} = Object.freeze([`];
  for (let i = 0; i < classes.length; i += 6) lines.push(`  ${classes.slice(i, i + 6).map((c) => `'${c}'`).join(', ')},`);
  lines.push(']);', '');
  return lines;
}

export function render({ background, normal, foreground, foremost }) {
  return [
    '// Generated by tools/build-item-bands.mjs from tinyspeck/glitch-GameServerJS and glitch-client (CC0). Do not edit.',
    '// The item holder each class draws in (LocationRenderer.placeItemstackInMG 1508-1517), back to front:',
    '// background < normal < foreground < other players < your avatar < foremost (MiddleGroundRenderer 111-171).',
    '',
    ...list('BACKGROUND_CLASSES', background, 'itemDef in_background: true -> BG_ITEM'),
    ...list('NORMAL_CLASSES', normal, 'neither flag -> NRM_ITEM'),
    ...list('FOREGROUND_CLASSES', foreground, 'itemDef in_foreground: true (and not in_background) -> FG_ITEM'),
    ...list('FOREMOST_CLASSES', foremost, 'Item.fromAnonymous 436-440 in_foremostground -> FOREMOST_ITEMS, over your avatar'),
  ].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const built = buildItemBands();
  const counts = Object.entries(built).map(([k, v]) => `${k} ${v.length}`).join(', ');
  if (process.argv.includes('--check')) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== render(built)) {
      console.error(`${OUT} is stale: run node tools/build-item-bands.mjs`);
      process.exit(1);
    }
    console.log(`item-bands-data.js is current (${counts})`);
  } else {
    writeFileSync(OUT, render(built));
    console.log(`${counts} -> ${OUT}`);
  }
}
