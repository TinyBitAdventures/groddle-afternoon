/**
 * Multiplayer phase 4: the race courses the realtime server referees
 * (the realtime server's races.go). For every course in public/js/race-courses.js it
 * writes what the server must own to judge a race between real players:
 *   - the two start points (config_prod.js multiplayer_quest_locations start
 *     points as the course rebuilt them: slot 0 stands where solo's player
 *     does, slot 1 where solo's stand-in rival does);
 *   - Grab 'Em Good: every game quoin's centre, in the course's order (the
 *     index a client claims), so a claim is checked against where the quoin
 *     really is and the total the win rule counts (global_game.js 454
 *     countItemClass('quoin'));
 *   - a finish-line race: the finish posts (location.js race_finish), so a
 *     "crossed the line" claim is checked against where the line is.
 * Titles and splash lines come from js/races.js (the GSJS strings).
 *
 * Run from the game repo root:
 *   node tools/build-realtime-races.mjs          (write)
 *   node tools/build-realtime-races.mjs --check  (fail when stale)
 * Writes data/races.json in the realtime server repo (go:embed in its races.go;
 * found by tools/repos.mjs: GRODDLE_SERVER_DIR, else ../groddle-afternoon-server).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { RACE_COURSE_IDS, raceCourse } from '../public/js/race-courses.js';
import { RACES } from '../public/js/races.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = serverPath('data', 'races.json');

const pt = (p) => [Math.round(p.x), Math.round(p.y)];

/** One course as the server reads it. */
export function courseRow(id) {
  const course = raceCourse(id);
  const race = RACES[id];
  if (!course || !race) return null;
  const quoins = course.kind === 'quoins';
  const row = {
    title: race.title,
    // config_prod.js shared_instances: quoin_grab for Grab 'Em Good, race for the seven.
    game: quoins ? 'quoin_grab' : 'race',
    kind: quoins ? 'quoins' : 'finish',
    spawns: [pt(course.spawn.player), pt(course.spawn.rival)],
  };
  if (quoins) row.quoins = course.quoins.map(pt);
  else row.finish = pt(course.finish);
  return row;
}

export function raceData() {
  const courses = {};
  for (const id of [...RACE_COURSE_IDS].sort()) {
    const row = courseRow(id);
    if (row) courses[id] = row;
  }
  return {
    about: 'Race courses for races.go in groddle-afternoon-server. Generated by tools/build-realtime-races.mjs from public/js/race-courses.js and js/races.js; do not edit by hand.',
    format: 'courses[id] = {title, game, kind, spawns:[[x,y],[x,y]], quoins:[[x,y]…] | finish:[x,y]}',
    courses,
  };
}

async function main() {
  requireServer();
  const out = raceData();
  const text = `${JSON.stringify(out)}\n`;
  const n = Object.keys(out.courses).length;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-races.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${n} courses)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${n} courses -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
