/**
 * The pack facts the site needs to give a multiplayer character its starter
 * bags (groddle-afternoon-site data/pack-slots.json, read by
 * src/LedgerStarter.php): for every tradeable class (the only classes the
 * ledger holds, assets/content/trade-items.json) the stack size, the bag
 * kinds that take it and its place in the auto-place order, plus the bags
 * themselves, all as js/pack-slots.js sees them in the browser
 * (features/bags-feature.js opts: the item catalog's stackMax and isToolItem,
 * the catalog's order). The site ports layoutPack (no saved arrangement) and
 * packIntoBags over this table, so a starter kit is the solo migration's kit
 * for the same holdings; tests/starter-bags-mp.test.js holds the two to the
 * same answers.
 *
 * Per class: [stack size (0: no limit), flags, order (-1: not in the catalog)].
 * Flags: t tool, x takes no slot, e element, s spice, c compound, u cubimal,
 * n no ordinary bag (no_bag tag).
 *
 * Run from the game repo root:
 *   node tools/build-site-pack-slots.mjs           writes the site repo's data/pack-slots.json
 *   node tools/build-site-pack-slots.mjs --check   exits 1 when it is stale
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireSite, sitePath } from './repos.mjs';
import { ITEM_CATALOG, isToolItem } from '../public/js/inventory.js?v=catalog-unified-7';
import { BAG_DEFS, PACK_CAPACITY, isBagClass, stackMaxOf, takesNoSlot } from '../public/js/pack-slots.js?v=g152-2';
import { COMPOUND_CLASSES, CUBIMAL_CLASSES, ELEMENT_CLASSES, NO_BAG_CLASSES, SPICE_CLASSES, TOOL_CLASSES } from '../public/js/pack-slots-data.js?v=g152-1';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = sitePath('data', 'pack-slots.json');

/** The table's JSON text. */
export function sitePackSlotsJson() {
  const trade = JSON.parse(readFileSync(join(root, 'public/assets/content/trade-items.json'), 'utf8'));
  const order = Object.keys(ITEM_CATALOG);
  const at = new Map(order.map((c, i) => [c, i]));
  const classes = {};
  for (const cls of Object.keys(trade.items || {}).sort()) {
    const max = stackMaxOf(cls, ITEM_CATALOG);
    let flags = '';
    if (TOOL_CLASSES.has(cls) || isToolItem(cls)) flags += 't';
    if (takesNoSlot(cls)) flags += 'x';
    if (ELEMENT_CLASSES.has(cls)) flags += 'e';
    if (SPICE_CLASSES.has(cls)) flags += 's';
    if (COMPOUND_CLASSES.has(cls)) flags += 'c';
    if (CUBIMAL_CLASSES.has(cls)) flags += 'u';
    if (NO_BAG_CLASSES.has(cls)) flags += 'n';
    classes[cls] = [Number.isFinite(max) ? max : 0, flags, at.has(cls) ? at.get(cls) : -1];
  }
  const bags = {};
  for (const [cls, def] of Object.entries(BAG_DEFS)) {
    if (!isBagClass(cls)) continue;
    bags[cls] = { cap: def.capacity, holds: def.holds, limited: def.limited, one: Boolean(def.onePerClass) };
  }
  return `${JSON.stringify({
    _doc: 'Generated by the game repo tools/build-site-pack-slots.mjs from js/pack-slots.js and the item catalog (do not edit). classes: tradeable class -> [stack size (0 no limit), flags (t tool, x no slot, e element, s spice, c compound, u cubimal, n no ordinary bag), auto-place order (-1 not in the catalog)]; bags: the bags and what they take.',
    capacity: PACK_CAPACITY,
    bags,
    classes,
  })}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  requireSite();
  const next = sitePackSlotsJson();
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (now !== next) {
      console.error('site data/pack-slots.json is stale: run node tools/build-site-pack-slots.mjs');
      process.exit(1);
    }
    console.log('data/pack-slots.json is current');
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT} (${next.length} bytes)`);
  }
}
