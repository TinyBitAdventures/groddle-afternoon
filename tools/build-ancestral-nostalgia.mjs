#!/usr/bin/env node
/**
 * Write public/js/ancestral-nostalgia-data.js: where Ancestral Nostalgia
 * sends you. do_baqala_boot (GSJS players/inc_special_locations.js 199-239)
 * picks one of 26 prod streets, then one of its incoming links
 * (geo_links_get_incoming: every signpost or door elsewhere that leads
 * there, with the point it lands you on). The remake's streets carry those
 * landing points on their signpost connects and door connects (`arrive`, in
 * the target street's screen space), so this collects, for each of the 26,
 * the arrivals of every imported street's signposts and doors that lead to it.
 *
 *   node tools/build-ancestral-nostalgia.mjs          write
 *   node tools/build-ancestral-nostalgia.mjs --check  exit 1 if the file is stale
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const streetsDir = join(root, 'public/assets/streets');
const OUT = join(root, 'public/js/ancestral-nostalgia-data.js');
const GSJS = join(root, '../glitch-GameServerJS/players/inc_special_locations.js');

/** inc_special_locations.js 200-225 (config.is_prod), in source order. */
export const BOOT_SOURCE_TSIDS = Object.freeze([
  'LHV17T973F42GEP', 'LHV1OOC40U42TKA', 'LHV9BF0AUJ42CLQ', 'LHV5B9093K42J9S', 'LHV144684H42FI4',
  'LHV14CBAO352I1I', 'LHV140E5N352BGF', 'LA51IOM1PC62SPF', 'LA51IVI7PC62L64', 'LA51CAQQ55629QM',
  'LA517JJML262LT0', 'LA517KBQL262H3U', 'LA517L6UL262RHT', 'LA51DOIHSK626VM', 'LA57FADCBN62PR0',
  'LIF14RQ7V872TPR', 'LIF18V95I972R96', 'LIF16PJS9972LC8', 'LIF14OKTU8722CQ', 'LIF14QE5V872L2E',
  'LIF14PFVU872CSG', 'LIF14TS9V872U9I', 'LA9117J18492SRS', 'LA9118S28492QCL', 'LA9JJL6KCE924IK',
  'LA912UEGE492F2G',
]);

const key = (tsid) => String(tsid || '').slice(1);

export function buildRows() {
  const index = JSON.parse(readFileSync(join(streetsDir, 'index.json'), 'utf8')).streets;
  const want = new Map(BOOT_SOURCE_TSIDS.map((t) => [key(t), t]));
  const arrivals = new Map(BOOT_SOURCE_TSIDS.map((t) => [key(t), new Map()]));
  const add = (target, arrive) => {
    const set = arrivals.get(key(target));
    if (!set || !arrive || !Number.isFinite(arrive.x) || !Number.isFinite(arrive.y)) return;
    set.set(`${Math.round(arrive.x)},${Math.round(arrive.y)}`, [Math.round(arrive.x), Math.round(arrive.y)]);
  };
  for (const [tsid, row] of Object.entries(index)) {
    const file = join(root, 'public', row.file || `assets/streets/${tsid}.json`);
    if (!existsSync(file)) continue;
    const street = JSON.parse(readFileSync(file, 'utf8'));
    for (const sign of street.signposts || []) for (const c of sign.connects || []) if (key(c.tsid) !== key(tsid)) add(c.tsid, c.arrive);
    for (const door of street.doors || []) if (door.connect && key(door.connect.tsid || door.connect.street) !== key(tsid)) add(door.connect.tsid || door.connect.street, door.connect.arrive);
  }
  const rows = [];
  for (const [k, source] of want) {
    const tsid = `G${k}`;
    const meta = index[tsid];
    if (!meta) continue;
    const points = [...arrivals.get(k).values()].sort((a, b) => a[0] - b[0] || a[1] - b[1]);
    rows.push({ tsid, source, label: meta.label, hubId: String(meta.hubId), arrivals: points });
  }
  return rows;
}

export function render(rows) {
  const lines = rows.map((r) => `  Object.freeze({ tsid: '${r.tsid}', source: '${r.source}', label: ${JSON.stringify(r.label)}, hubId: '${r.hubId}', arrivals: Object.freeze(${JSON.stringify(r.arrivals)}) }),`);
  return `/**
 * Generated by tools/build-ancestral-nostalgia.mjs (do not edit): the 26
 * streets do_baqala_boot sends you to (GSJS players/inc_special_locations.js
 * 199-226, prod list, source order) and, for each, the landing points of the
 * signposts and doors elsewhere that lead there (geo_links_get_incoming), in
 * the street's screen space.
 */

export const NOSTALGIA_BOOT_STREETS = Object.freeze([
${lines.join('\n')}
]);
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const check = process.argv.includes('--check');
  if (existsSync(GSJS)) {
    const src = readFileSync(GSJS, 'utf8');
    const list = [...src.slice(src.indexOf('config.is_prod')).matchAll(/"(L[A-Z0-9]{14})"/g)].map((m) => m[1]);
    if (list.join() !== BOOT_SOURCE_TSIDS.join()) {
      console.error('BOOT_SOURCE_TSIDS no longer matches inc_special_locations.js');
      process.exit(1);
    }
  }
  const text = render(buildRows());
  const before = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (check) {
    if (before !== text) {
      console.error('stale: public/js/ancestral-nostalgia-data.js (node tools/build-ancestral-nostalgia.mjs)');
      process.exit(1);
    }
    console.log('ancestral-nostalgia-data.js is current');
  } else {
    if (before !== text) writeFileSync(OUT, text);
    const rows = buildRows();
    console.log(`${rows.length} streets, ${rows.reduce((n, r) => n + r.arrivals.length, 0)} arrivals`);
  }
}
