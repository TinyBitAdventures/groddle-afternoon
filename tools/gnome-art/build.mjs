#!/usr/bin/env node
/**
 * The Garden Gnome's frames (G435), from Tiny Speck's CC0 file.
 *
 * glitch-items misc/npc/npc_garden_gnome/npc_garden_gnome.swf has one animated symbol, sprite 31
 * (placed on the root as gardenGnome, no scale), 140 frames at 24 fps with the labels the server's
 * states name (items/npc_garden_gnome.js setAndBroadcastState): idle0, idleBlink, bounce, hopStart,
 * hopLoop, hopEnd, talk, look, lookSettle. OpenGameArt has no gnome sheet. FFDec exports every frame
 * on one shared 83 x 152 canvas (its bottom is the ground: frame 1's feet and shadow end there, as
 * the getAssetInfo box {x:-41, y:-129, w:83, h:129} does, npc_garden_gnome.js 794-796).
 *
 * Only 80 of the 140 frames differ (held drawings repeat), so the sheet holds each drawing once and
 * GNOME_ART.frames maps every SWF frame to its cell. All 140 frames and every label ship; 'bounce'
 * is no state the server sets, so nothing plays it.
 *
 * Output:
 *   public/assets/sprites/garden-gnome/npc_garden_gnome.webp  the 1x sheet (80 cells, 10 across;
 *                                                             lossless WebP, a third smaller than PNG)
 *   public/js/garden-gnome-art.js                             (generated: cell, frames, labels)
 * The sharp 3x file is tools/vector-sprites/garden-gnome.json (node tools/vector-sprites/build.mjs
 * --manifest tools/vector-sprites/garden-gnome.json), which reads frameList from this module.
 *
 * Usage: node tools/gnome-art/build.mjs [--work <dir>] [--check]
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { FFDEC, JAVA, swfSprites } from '../vector-sprites/swf-labels.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const SWF = join(os.homedir(), 'Documents/glitch-audit/glitch-items/misc/npc/npc_garden_gnome/npc_garden_gnome.swf');
const SPRITE = 31;
const COLS = 10;
const FPS = 24;
const OUT_DIR = join(ROOT, 'public/assets/sprites/garden-gnome');
const OUT_PNG = join(OUT_DIR, 'npc_garden_gnome.webp');
const OUT_JS = join(ROOT, 'public/js/garden-gnome-art.js');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const WORK = opt('--work', join(os.tmpdir(), 'gnome-art-work'));
const CHECK = args.includes('--check');
/** Labels that loop while their state lasts; every other label plays once and holds its last frame. */
const LOOPS = ['hopLoop', 'talk'];

function size(png) {
  return execFileSync('magick', ['identify', '-format', '%w %h', png], { encoding: 'utf8' }).trim().split(' ').map(Number);
}
function rgba(png) {
  const [w, h] = size(png);
  return { w, h, data: execFileSync('magick', [png, '-depth', '8', 'RGBA:-'], { maxBuffer: 1 << 28 }) };
}

const dir = join(WORK, `DefineSprite_${SPRITE}`);
if (!existsSync(dir) || readdirSync(dir).length < 140) {
  mkdirSync(WORK, { recursive: true });
  execFileSync(JAVA, ['-jar', FFDEC, '-zoom', '1', '-selectid', String(SPRITE), '-format', 'sprite:png', '-export', 'sprite', WORK, SWF], { stdio: 'ignore', timeout: 600000 });
}
const sprite = swfSprites(SWF).find((s) => s.id === SPRITE);
if (!sprite || sprite.frames !== 140) throw new Error(`sprite ${SPRITE} is not the 140-frame gnome`);
const frames = Array.from({ length: sprite.frames }, (_, i) => rgba(join(dir, `${i + 1}.png`)));
const cell = { w: frames[0].w, h: frames[0].h };
if (frames.some((f) => f.w !== cell.w || f.h !== cell.h)) throw new Error('frames do not share one canvas');

const seen = new Map();
const unique = [];
const map = frames.map((f, i) => {
  const key = createHash('sha256').update(f.data).digest('hex');
  if (!seen.has(key)) {
    seen.set(key, unique.length);
    unique.push(i + 1);
  }
  return seen.get(key);
});

const rows = Math.ceil(unique.length / COLS);
const sheet = Buffer.alloc(cell.w * COLS * cell.h * rows * 4);
unique.forEach((n, k) => {
  const f = frames[n - 1];
  const cx = (k % COLS) * cell.w;
  const cy = Math.floor(k / COLS) * cell.h;
  for (let y = 0; y < cell.h; y += 1) f.data.copy(sheet, ((cy + y) * cell.w * COLS + cx) * 4, y * cell.w * 4, (y + 1) * cell.w * 4);
});

const art = {
  file: 'npc_garden_gnome.webp',
  cell,
  cols: COLS,
  cells: unique.length,
  fps: FPS,
  anchor: { x: 0.5, y: 1 },
  frames: map,
  swfFrames: unique,
  labels: Object.fromEntries(sprite.labels.map((l) => [l.name, [l.start - 1, l.count]])),
  loops: LOOPS,
};
const js = [
  '/**',
  ' * GENERATED by tools/gnome-art/build.mjs. Do not edit.',
  ' *',
  ' * The Garden Gnome: glitch-items npc_garden_gnome.swf (CC0) sprite 31, 140 frames at 24 fps.',
  ' * frames[i] is the sheet cell of SWF frame i + 1 (80 different drawings); labels are',
  ' * [first frame (0-based), count]; swfFrames[k] is the SWF frame cell k shows. Labels in loops',
  ' * repeat while their state lasts; the rest play once and hold their last frame.',
  ' */',
  "export const GNOME_ART_DIR = 'assets/sprites/garden-gnome/';",
  `export const GNOME_ART = Object.freeze(${JSON.stringify(art)});`,
  '',
].join('\n');

if (CHECK) {
  const have = existsSync(OUT_JS) ? readFileSync(OUT_JS, 'utf8') : '';
  const png = existsSync(OUT_PNG) ? rgba(OUT_PNG) : null;
  if (have !== js || !png || !png.data.equals(sheet)) {
    console.error('garden gnome art is stale: run node tools/gnome-art/build.mjs');
    process.exit(1);
  }
  console.log(`garden gnome art is current (${unique.length} cells for ${frames.length} frames)`);
  process.exit(0);
}
mkdirSync(OUT_DIR, { recursive: true });
const tmp = join(WORK, 'sheet.png');
execFileSync('magick', ['-size', `${cell.w * COLS}x${cell.h * rows}`, '-depth', '8', 'RGBA:-', `PNG32:${tmp}`], { input: sheet, maxBuffer: 1 << 28 });
execFileSync('cwebp', ['-quiet', '-lossless', '-exact', '-z', '9', tmp, '-o', OUT_PNG]);
writeFileSync(OUT_JS, js);
console.log(`garden gnome: ${unique.length} cells for ${frames.length} frames -> ${OUT_PNG}`);
