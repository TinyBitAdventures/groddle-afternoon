/**
 * The Ur subway between real players (register G115, online in lane MPPUBLIC):
 * what the realtime server's subway.go needs to run shared trains. From
 * public/js/subway.js (SUBWAY_LINE, generated from config_prod.js
 * transit_instances.subway_1, and the remake's rideTiming):
 *   - every station's id, name, platform street and its next (Red Line,
 *     next_stop) and previous (Blue Line, previous_stop) stops;
 *   - min_capacity 3, max_capacity 10, initial_departure_timeout 60 s and
 *     departure_timeout 10 s (the dwell at a stop), as in the source;
 *   - the remake's own ride times (subway.js rideTiming): 20 s between stops
 *     (source arrival_timeout 30), the doors 3 s before departure
 *     (inc_transit.js 245-248, 261-263), and the 10 s a lone rider waits.
 *
 * Run from the game repo root:
 *   node tools/build-realtime-subway.mjs          (write)
 *   node tools/build-realtime-subway.mjs --check  (fail when stale)
 * Writes data/subway.json in the realtime server repo (go:embed in its subway.go;
 * found by tools/repos.mjs: GRODDLE_SERVER_DIR, else ../groddle-afternoon-server).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { STATIONS, SUBWAY_LINE, rideTiming } from '../public/js/subway.js?v=e6995db8';

const outPath = serverPath('data', 'subway.json');

export function subwayData() {
  const t = rideTiming(1);
  const s = (ms) => Math.round(ms / 1000);
  return {
    about: 'The Ur subway for subway.go in groddle-afternoon-server. Generated by tools/build-realtime-subway.mjs from public/js/subway.js (config_prod.js transit_instances.subway_1 and the remake ride times); do not edit by hand.',
    format: 'stations[] = {id, name, street, next, prev}; times in seconds',
    min_capacity: SUBWAY_LINE.min_capacity,
    max_capacity: SUBWAY_LINE.max_capacity,
    initial_departure_timeout: SUBWAY_LINE.initial_departure_timeout,
    departure_timeout: SUBWAY_LINE.departure_timeout,
    lonely: s(t.board),
    doors: s(t.doors),
    travel: s(t.travel),
    stations: STATIONS.map((st) => ({ id: st.id, name: st.name, street: st.streetTsid, next: st.next_stop, prev: st.previous_stop })),
  };
}

async function main() {
  requireServer();
  const out = subwayData();
  const text = `${JSON.stringify(out)}\n`;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-subway.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${out.stations.length} stations)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${out.stations.length} stations -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
