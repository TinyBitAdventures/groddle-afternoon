/**
 * G260: which streets hold a Qurazy marker (items/marker_qurazy.js), from
 * Tiny Speck's archived locations-xml (CC0). The L-prefixed location objects
 * list each street's items as `<objref tsid=... label="Qurazy marker"/>`;
 * their x/y lived on the item records, which were never archived, so only the
 * count per street survives. Writes public/js/qurazy-markers.js.
 *
 * Run from spike root:
 *   node tools/build-qurazy-markers.mjs
 * GRODDLE_LOCATION_XML overrides the location_data folder.
 */

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const locationRoot =
  process.env.GRODDLE_LOCATION_XML ||
  '/Users/austin/Documents/glitch-audit/streets/mnt/stos/location_data';
const outputPath = join(root, 'public/js/qurazy-markers.js');

const files = (await readdir(locationRoot)).filter((f) => /^L[A-Z0-9]+\.xml$/.test(f)).sort();
const ones = [];
const twos = [];
for (const file of files) {
  const xml = await readFile(join(locationRoot, file), 'utf8');
  const count = (xml.match(/label="Qurazy marker"/g) || []).length;
  if (!count) continue;
  const tsid = `G${file.slice(1, -4)}`;
  if (count === 1) ones.push(tsid);
  else twos.push(tsid);
  if (count > 2) throw new Error(`${file}: ${count} markers, the format only knows 1 or 2`);
}

const wrap = (list) => {
  const lines = [];
  for (let i = 0; i < list.length; i += 6) lines.push(`  '${list.slice(i, i + 6).join(' ')}',`);
  return lines.join('\n');
};

const out = `/**
 * G260: streets with a Qurazy marker (items/marker_qurazy.js) in Tiny Speck's
 * archived locations-xml (CC0, the L-prefixed late-game location objects):
 * ${ones.length + twos.length} of ${files.length} locations, ${twos.length} of them with two. Only the count survives:
 * the markers' x/y were on item records that were never archived.
 * Generated by tools/build-qurazy-markers.mjs; do not edit by hand.
 */

const ONE = [
${wrap(ones)}
].join(' ');

const TWO = [
${wrap(twos)}
].join(' ');

const COUNTS = new Map();
for (const tsid of ONE.split(' ')) if (tsid) COUNTS.set(tsid, 1);
for (const tsid of TWO.split(' ')) if (tsid) COUNTS.set(tsid, 2);

export const QURAZY_MARKER_STREET_COUNT = COUNTS.size;

/** How many Qurazy markers a street (G- or L-prefixed tsid) holds; 0 for none. */
export function qurazyMarkersFor(tsid) {
  const key = String(tsid || '');
  return COUNTS.get(key.startsWith('L') ? \`G\${key.slice(1)}\` : key) || 0;
}
`;

await writeFile(outputPath, out);
console.log(`${outputPath}: ${ones.length + twos.length} streets (${twos.length} with two) of ${files.length} locations`);
