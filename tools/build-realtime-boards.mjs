/**
 * Notice Boards shared between real players (Austin 2026-11-04): what the
 * realtime server's boards.go needs to run them. From the game's own data:
 *   - every street with a board: the archived rows with a bag_notice_board in
 *     assets/content/street-ecology.json (7, build-street-ecology.mjs
 *     `furniture`) and the three Community Machine Rooms, whose board
 *     js/machine-rooms.js hangs on the wall (G169);
 *   - the notices each board starts with (js/street-furniture.js BOARD_PINS,
 *     the remake's own words, marked as such), pinned online once;
 *   - capacity 10 (items/bag_notice_board.js onCreate 155) and the note's
 *     150 / 1000 character limits (items/note.js 246-247);
 *   - every text the remake wrote for notes (REMAKE_NOTE_TEXTS: STREET_NOTES,
 *     BOARD_PINS, the retired pins and the old words of reworded ones), so a
 *     remake note pinned again keeps its marker.
 *
 * Run from the game repo root:
 *   node tools/build-realtime-boards.mjs          (write)
 *   node tools/build-realtime-boards.mjs --check  (fail when stale)
 * Writes data/boards.json in the realtime server repo (go:embed in its boards.go;
 * found by tools/repos.mjs: GRODDLE_SERVER_DIR, else ../groddle-afternoon-server).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { BOARD_CAPACITY, BOARD_CLASS, NOTE_LIMITS, REMAKE_NOTE_TEXTS, boardPinSeeds } from '../public/js/street-furniture.js?v=55131f49';
import { MACHINE_ROOM_TSIDS } from '../public/js/machine-rooms.js?v=0a46ca80';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = serverPath('data', 'boards.json');

/** The streets that hang a Notice Board, sorted. */
export function boardStreets() {
  const ecology = JSON.parse(readFileSync(join(root, 'public/assets/content/street-ecology.json'), 'utf8'));
  const out = new Set();
  for (const [tsid, row] of Object.entries(ecology.furniture || {})) {
    if (Number(row?.[BOARD_CLASS]) > 0) out.add(tsid.replace(/^L/, 'G'));
  }
  for (const tsid of MACHINE_ROOM_TSIDS) out.add(String(tsid).replace(/^L/, 'G'));
  return [...out].sort();
}

export function boardsData() {
  const boards = {};
  for (const tsid of boardStreets()) {
    boards[tsid] = { seeds: boardPinSeeds(tsid).map((n) => ({ title: n.initialTitle, body: n.initialText })) };
  }
  const remake = [...REMAKE_NOTE_TEXTS];
  return {
    about: 'Notice Boards for boards.go in groddle-afternoon-server. Generated by tools/build-realtime-boards.mjs from public/js/street-furniture.js (BOARD_PINS, STREET_NOTES), public/js/machine-rooms.js and assets/content/street-ecology.json; do not edit by hand.',
    format: 'boards{street: {seeds[] = {title, body}}}: the streets with a board and the remake notices each starts with; remake[]: note bodies the remake wrote',
    capacity: BOARD_CAPACITY,
    title: NOTE_LIMITS.title,
    body: NOTE_LIMITS.body,
    boards,
    remake,
  };
}

async function main() {
  requireServer();
  const out = boardsData();
  const text = `${JSON.stringify(out)}\n`;
  const n = Object.keys(out.boards).length;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-boards.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${n} boards)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${n} boards -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
