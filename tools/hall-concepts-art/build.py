#!/usr/bin/env python3.11
"""The Hall of Rejected Concepts exhibits (register row G73), rendered from Tiny Speck's museum_* decos.

The Hall (LA9L33D5CNE3I0J, hub 96 "Jethimadh Tower: Mid" in inc_data_maps_prod.js) is not in the
public locations dump, so its deco list and geometry are lost. Ten player Snaps
(research/wayback/raw/snaps/jtower_hall_rejected_concepts/) and two player recordings
(reference-videos/raw/-03T3bLY7a0.mp4, E6BIN3OfEkI.mp4), all reference only, show every exhibit, and
each one exists as a CC0 deco SWF in tinyspeck/glitch-locations source/quests/museum_*.swf. The plinth is
museum_stand_1. js/hall-rejected-concepts.js lays them out.

This reuses the street deco pipeline (tools/deco-pipeline/build.py): FFDec renders each SWF's first frame
at zoom 3 (render_batch), the render is trimmed to its visible pixels and encoded as WebP (encode: lossy
q82 sharp YUV, lossless where the lossy file shows artefacts). Exhibits are drawn at their SWF stage size
(world px = stage px), so each file is <name>@3x.webp and js/textures.js gives the sprite its world size.

Writes public/assets/sprites/quests/hall-rejected-concepts/<name>@3x.webp,
tools/hall-concepts-art/plan.json and public/js/hall-concepts-art.js (generated: file, world size and
the trim offset per piece).

Usage (python3.11 has numpy + Pillow; FFDec needs Java 21; cwebp):
  python3.11 -I tools/hall-concepts-art/build.py --work <scratch dir>
  python3.11 -I tools/hall-concepts-art/build.py --check     (no rendering; exit 1 on a problem)
Glitch-locations is data only: the SWFs are read by FFDec, never executed.
"""
import argparse, hashlib, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SPIKE = os.path.dirname(os.path.dirname(HERE))
sys.dont_write_bytecode = True
for sub in ('deco-audit', 'icon-hires', 'deco-pipeline'):
    sys.path.insert(0, os.path.join(SPIKE, 'tools', sub))
import build as deco  # noqa: E402  (tools/deco-pipeline/build.py)
from PIL import Image  # noqa: E402

SRC = os.path.expanduser('~/Documents/glitch-audit/research/audio-hunt/raw/glitch-locations/source/quests')
OUT = os.path.join(SPIKE, 'public', 'assets', 'sprites', 'quests', 'hall-rejected-concepts')
PLAN = os.path.join(HERE, 'plan.json')
OUT_JS = os.path.join(SPIKE, 'public', 'js', 'hall-concepts-art.js')
ZOOM = 3

# Every museum_* deco the Snaps and recordings show in the Hall. museum_abbasidss_1, museum_flyingkitties_1
# and museum_woodtree_1 are in the same folder but appear in neither, so they are left out.
PIECES = [
    'museum_rube_1', 'museum_fox_1', 'museum_craftybot_1', 'museum_butler_1', 'museum_deimaginator_1',
    'museum_ssgroddle_1', 'museum_ssgroddle_2', 'museum_bunny_1', 'museum_dragon_1', 'museum_foodvendor_1',
    'museum_gardeningvendor_1', 'museum_wishdolly_1', 'museum_playerator_1', 'museum_tools_1',
    'museum_stactus_1', 'museum_avatars_1', 'museum_stand_1',
]


def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()[:16]


def build(work):
    os.makedirs(OUT, exist_ok=True)
    items = [(n, os.path.join(SRC, n + '.swf')) for n in PIECES]
    found, _ = deco.render_batch(work, ZOOM, items)
    rows = []
    for name in PIECES:
        if name not in found:
            raise SystemExit(f'FFDec did not render {name}')
        img = Image.open(found[name]).convert('RGBA')
        box = img.getchannel('A').point(lambda a: 255 if a > 2 else 0).getbbox()
        # Keep whole world pixels: pad the trim to multiples of ZOOM from the stage origin.
        l, t = box[0] // ZOOM * ZOOM, box[1] // ZOOM * ZOOM
        r, b = -(-box[2] // ZOOM) * ZOOM, -(-box[3] // ZOOM) * ZOOM
        crop = Image.new('RGBA', (r - l, b - t), (0, 0, 0, 0))
        crop.paste(img.crop((l, t, min(r, img.width), min(b, img.height))), (0, 0))
        dst = os.path.join(OUT, f'{name}@{ZOOM}x.webp')
        size, lossless, err = deco.encode(crop, dst, os.path.join(work, 'enc'))
        rows.append({
            'name': name,
            'swf': sha(os.path.join(SRC, name + '.swf')),
            'stage': [-(-img.width // ZOOM), -(-img.height // ZOOM)],
            'trim': [l // ZOOM, t // ZOOM],
            'w': crop.width // ZOOM,
            'h': crop.height // ZOOM,
            'bytes': size,
            'lossless': lossless,
            'error': err,
            'webp': sha(dst),
        })
        print(f'{name}: {crop.width}x{crop.height} {size} B{" lossless" if lossless else ""}')
    json.dump({'zoom': ZOOM, 'pieces': rows}, open(PLAN, 'w'), indent=1)
    open(PLAN, 'a').write('\n')
    write_js(rows)


def write_js(rows):
    lines = [
        '// Generated by tools/hall-concepts-art/build.py: do not edit.',
        '// The Hall of Rejected Concepts exhibit art (tinyspeck/glitch-locations source/quests/museum_*.swf, CC0),',
        '// FFDec at zoom 3, trimmed: world size w x h, trim = the top-left of the trim in the SWF stage (world px).',
        "export const HALL_ART_ROOT = 'assets/sprites/quests/hall-rejected-concepts/';",
        'export const HALL_ART = Object.freeze({',
    ]
    for r in rows:
        lines.append(f"  {r['name']}: Object.freeze({{ file: '{r['name']}@{ZOOM}x.webp', w: {r['w']}, h: {r['h']}, "
                     f"stage: [{r['stage'][0]}, {r['stage'][1]}], trim: [{r['trim'][0]}, {r['trim'][1]}] }}),")
    lines.append('});')
    open(OUT_JS, 'w').write('\n'.join(lines) + '\n')


def check():
    bad = []
    plan = json.load(open(PLAN))
    for r in plan['pieces']:
        dst = os.path.join(OUT, f"{r['name']}@{ZOOM}x.webp")
        if not os.path.exists(dst):
            bad.append(f'missing {dst}')
            continue
        if sha(dst) != r['webp']:
            bad.append(f'{dst} changed')
        if sha(os.path.join(SRC, r['name'] + '.swf')) != r['swf']:
            bad.append(f"{r['name']}.swf changed")
        with Image.open(dst) as im:
            if im.size != (r['w'] * ZOOM, r['h'] * ZOOM):
                bad.append(f'{dst} is {im.size}')
    if [r['name'] for r in plan['pieces']] != PIECES:
        bad.append('plan.json pieces differ from PIECES')
    for b in bad:
        print(b)
    print('ok' if not bad else f'{len(bad)} problem(s)')
    return 1 if bad else 0


if __name__ == '__main__':
    a = argparse.ArgumentParser()
    a.add_argument('--work')
    a.add_argument('--check', action='store_true')
    args = a.parse_args()
    if args.check:
        sys.exit(check())
    if not args.work:
        a.error('--work <scratch dir> is required to build')
    build(args.work)
