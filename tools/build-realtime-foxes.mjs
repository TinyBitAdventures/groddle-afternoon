/**
 * G329 / G134 fox_flurrier: the Fox Brushing Preserves the realtime server
 * shares between real players (the realtime server's foxes.go). It writes
 * what the server must own to decide how many foxes a preserve has, never
 * from what a client says:
 *   - the preserves: every street whose archived items include a Fox Ranger
 *     (assets/content/street-ecology.json wildlife, isPreserveRow);
 *   - spawn_fox (locations/inc_npcs.js:130-160): one fox per three active
 *     players (players / 3, a float), at most one spawn timer;
 *   - the timers: ignite's 4 s spawn (fox_bait.js:117), the 10 s respawn after
 *     a fox brushed out with bait left (npc_fox.js:433), bait's 5 minutes
 *     (location.js:4357), three baits a drop (location.js:4349);
 *   - when a fox leaves: three brushers or 21 brushes (npc_fox.js:425), no
 *     bait left (startMoving), the 2 s brush cooldown (npc_fox.js:212);
 *   - the crowded-bait gate: more than four placed baits within 400 px
 *     (fox_bait.js ignite conditions);
 *   - the words: "A fox appears!", "The fox leaves...", "No more bait
 *     remains, so the Fox leaves...".
 *
 * Run from the game repo root:
 *   node tools/build-realtime-foxes.mjs          (write)
 *   node tools/build-realtime-foxes.mjs --check  (fail when stale)
 * Writes data/foxes.json in the realtime server repo (go:embed in its
 * foxes.go; found by tools/repos.mjs: GRODDLE_SERVER_DIR, else
 * ../groddle-afternoon-server).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { FOX_TEXT, FOX_TIMING } from '../public/js/foxes.js?v=9534264f';
import { FOX_LEAVE_MS, FOX_PLAYERS_PER_FOX } from '../public/js/foxes-mp.js?v=4f8bf0eb';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outPath = serverPath('data', 'foxes.json');

/** isPreserveRow (features/foxes-feature.js): a street whose archived items include a Fox Ranger. */
export function preserveStreets() {
  const eco = JSON.parse(readFileSync(join(root, 'public', 'assets', 'content', 'street-ecology.json'), 'utf8'));
  return Object.entries(eco.wildlife || {})
    .filter(([, row]) => Number(row?.npc_fox_ranger) > 0)
    .map(([tsid]) => tsid)
    .sort();
}

export function foxesData() {
  return {
    about: 'The Fox Brushing Preserves for foxes.go in groddle-afternoon-server. Generated by tools/build-realtime-foxes.mjs from public/js/foxes.js, public/js/foxes-mp.js and assets/content/street-ecology.json; do not edit by hand.',
    format: 'street tsids; ms; px',
    preserves: preserveStreets(),
    playersPerFox: FOX_PLAYERS_PER_FOX,
    spawnDelayMs: FOX_TIMING.spawnDelayMs,
    respawnAfterLeaveMs: FOX_TIMING.respawnAfterLeaveMs,
    leaveMs: FOX_LEAVE_MS,
    baitExpireMs: FOX_TIMING.baitExpireMs,
    baitDropCount: FOX_TIMING.baitDropCount,
    baitDropSpread: FOX_TIMING.baitDropSpread,
    baitDropSpacing: FOX_TIMING.baitDropSpacing,
    baitCrowdRadius: FOX_TIMING.baitCrowdRadius,
    baitCrowdMax: FOX_TIMING.baitCrowdMax,
    maxBrushes: FOX_TIMING.maxBrushes,
    maxBrushers: FOX_TIMING.maxBrushers,
    brushCooldownMs: FOX_TIMING.brushCooldownMs,
    text: {
      appears: FOX_TEXT.appears,
      leaves: FOX_TEXT.leaves,
      leavesNoBait: FOX_TEXT.leavesNoBait,
      crowded: FOX_TEXT.igniteCrowded,
      notPreserve: FOX_TEXT.igniteNotPreserve,
    },
  };
}

async function main() {
  requireServer();
  const text = `${JSON.stringify(foxesData())}\n`;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-foxes.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`fox preserves -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
