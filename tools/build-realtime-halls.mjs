/**
 * The Bureaucratic Halls between real players (register G479, lane MPPUBLIC):
 * what the realtime server's halls.go needs to keep each hall's bureaucrats
 * shared. From public/js/bureaucratic-hall.js and
 * features/bureaucratic-halls-feature.js:
 *   - the three street halls (their scene streets HALL_<tsid>; Legalize It's
 *     own hall stays the player's);
 *   - the bureaucrats: four, their names (legalize-it.js LEGALIZE_CLERKS) and
 *     where each starts behind the counter (ours, HALL_LAYOUT.clerkHomes);
 *   - idle_onMsg's stroll (npc_bureaucrat.js 733-745: 25% each interval, to
 *     x 500-1060 at 20-40 px/s, else maybe turn round; the next interval 1-10 s)
 *     and returnToStart's walk (60 px/s, see bureaucratic-hall.js WALK_SPEED);
 *   - the remake's turn timeout and the helping reminder (8 s).
 *
 * Run from the game repo root:
 *   node tools/build-realtime-halls.mjs          (write)
 *   node tools/build-realtime-halls.mjs --check  (fail when stale)
 * Writes data/halls.json in the realtime server repo (go:embed in its halls.go).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { HALL_LAYOUT, REMINDER_MS, WALK_SPEED } from '../public/js/bureaucratic-hall.js?v=a0bc6317';
import { HALL_TURN_MS } from '../public/js/halls-mp.js?v=044b5c5a';
import { HALL_DOORS, hallSceneTsid } from '../public/js/features/bureaucratic-halls-feature.js?v=61fb488c';
import { LEGALIZE_CLERKS } from '../public/js/legalize-it.js?v=b5645cb6';

const outPath = serverPath('data', 'halls.json');

export function hallsData() {
  return {
    about: 'The Bureaucratic Halls for halls.go in groddle-afternoon-server. Generated by tools/build-realtime-halls.mjs from public/js/bureaucratic-hall.js and features/bureaucratic-halls-feature.js; do not edit by hand.',
    format: 'halls[] = {street, label}; clerks[] = {name, home}; stroll [x0, x1], speeds px/s, times ms',
    halls: Object.values(HALL_DOORS).map((d) => ({ street: hallSceneTsid(d.tsid), label: d.label })).sort((a, b) => a.street.localeCompare(b.street)),
    clerks: LEGALIZE_CLERKS.map((c, i) => ({ name: c.name, home: HALL_LAYOUT.clerkHomes[i] })),
    stroll: [...HALL_LAYOUT.stroll],
    stroll_speed: [20, 40],
    walk_speed: WALK_SPEED,
    reminder: REMINDER_MS,
    turn: HALL_TURN_MS,
  };
}

async function main() {
  requireServer();
  const out = hallsData();
  const text = `${JSON.stringify(out)}\n`;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-halls.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${out.halls.length} halls)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${out.halls.length} halls -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
