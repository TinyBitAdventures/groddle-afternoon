/**
 * Furniture plats players stand on (#772), written as public/js/furniture-plats-data.js.
 *
 * In Glitch a placed piece added its plats to the room (locations/inc_geo.js geo_add_plats_from_item
 * 934-953, main.js doFurnitureDrop 7031; restored when the house loads, inc_homes.js 815-821;
 * swapped on an upgrade or a flip, items/include/furniture.js applyUpgrade / flipPlats), and a plat
 * with platform_pc_perm -1 is solid from the top for players (glitch-client PlatformLine.as 341): a
 * player stood on a table, a chair, a bed or a shelf as on any street ledge.
 *
 * Source (tinyspeck/glitch-GameServerJS, CC0):
 * - items/<class>.js getFurnitureBaseGeo   the plain piece's plats ("generated by the furniture
 *                                          plat editor"; furniture-upgrades/build.mjs basePlats)
 * - items/catalog_furniture.js             each upgrade's plats (include/furniture.js
 *                                          getPlatsAndWalls: an upgrade with plats or walls uses its
 *                                          own, else the plain piece's)
 * Plats are measured from the SWF stage's bottom centre, the point the original placed a piece by.
 * The remake draws a piece's trimmed art centred on its x with the art's bottom on its y, so each line
 * here is moved by the art's foot (how far its bottom sits over that point) and cx (how far its centre
 * sits right of it), both measured by tools/furniture-upgrades/render.py (base.json for the plain
 * pieces' frames, art.json for the upgrades). Only platform_pc_perm -1 plats are kept: the 14
 * pc_perm 0 ones (Fireplace hearths, one bed style) let players walk through (AvatarPhysicsHandler.as
 * 955-957), so they are no line for the avatar.
 *
 * Each row is [x1, y1, x2, y2] in px from the drawn art's bottom centre, facing right (y up is
 * negative). js/home-decor.js furniturePlatforms flips x for a piece facing left, as getPlatsAndWalls
 * mirrored a plat about the piece's point.
 *
 *   node tools/furniture-plats/build.mjs           write the data module
 *   node tools/furniture-plats/build.mjs --check   exit 1 when it is stale
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { basePlats, loadCatalog } from '../furniture-upgrades/build.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const AUDIT = join(process.env.HOME || '', 'Documents/glitch-audit');
const GSJS = process.env.GLITCH_GSJS || join(AUDIT, 'glitch-GameServerJS');
const OUT = join(root, 'public/js/furniture-plats-data.js');
const BASE_ART = join(root, 'tools/furniture-upgrades/base.json');
const UPGRADE_ART = join(root, 'tools/furniture-upgrades/art.json');

/** platform_pc_perm -1: solid from the top for players (PlatformLine.as pc_solid_from_top). */
const standable = (p) => p?.start && p?.end && Number(p.platform_pc_perm) === -1;

/** A source plat as a line from the drawn art's bottom centre: x less cx, y plus foot. */
function line(p, foot, cx) {
  return [p.start.x - cx, p.start.y + foot, p.end.x - cx, p.end.y + foot].map((v) => Math.round(v));
}

function lines(plats, foot, cx) {
  return Object.values(plats || {}).filter(standable).map((p) => line(p, foot, cx));
}

export async function build() {
  const { FURNITURE_CATALOG } = await import(join(root, 'public/js/homes-catalog.js'));
  const { FURNITURE_UPGRADES } = await import(join(root, 'public/js/furniture-upgrades-data.js'));
  const baseArt = JSON.parse(readFileSync(BASE_ART, 'utf8'));
  const upArt = JSON.parse(readFileSync(UPGRADE_ART, 'utf8'));
  const catalog = loadCatalog();
  const out = {};
  const counts = { classes: 0, base: 0, upgrades: 0, lines: 0, passThrough: 0 };
  const unmeasured = [];
  for (const [cls, def] of Object.entries(FURNITURE_CATALOG)) {
    const row = {};
    // The plain piece: its frame is the base SWF's when build-homes gave it a foot (base.json).
    const plain = basePlats(cls, GSJS);
    if (plain) {
      counts.passThrough += Object.values(plain).filter((p) => p?.start && !standable(p)).length;
      const cx = baseArt[cls]?.cx;
      if (Number.isFinite(def.art?.foot) && Number.isFinite(cx)) {
        const got = lines(plain, def.art.foot, cx);
        if (got.length) {
          row.base = got;
          counts.base += 1;
          counts.lines += got.length;
        }
      } else if (Object.values(plain).some(standable)) unmeasured.push(`${cls}/0`);
    }
    // Each upgrade the remake draws (its art in furniture-upgrades-data.js).
    const ups = {};
    for (const [id, u] of Object.entries(catalog[cls] || {})) {
      const art = FURNITURE_UPGRADES[cls]?.upgrades?.[id]?.art;
      if (!art) continue;
      // getPlatsAndWalls: the upgrade's own plats when it has plats or walls, else the plain piece's.
      const plats = u.plats || u.walls ? u.plats : plain;
      counts.passThrough += Object.values(plats || {}).filter((p) => p?.start && !standable(p)).length;
      if (!Object.values(plats || {}).some(standable)) continue;
      const cx = upArt[`${cls}/${id}`]?.cx;
      if (!Number.isFinite(art.foot) || !Number.isFinite(cx)) {
        unmeasured.push(`${cls}/${id}`);
        continue;
      }
      ups[id] = lines(plats, art.foot, cx);
      counts.upgrades += 1;
      counts.lines += ups[id].length;
    }
    if (Object.keys(ups).length) row.upgrades = ups;
    if (Object.keys(row).length) {
      out[cls] = row;
      counts.classes += 1;
    }
  }
  return { plats: out, counts, unmeasured };
}

function render({ plats, counts, unmeasured }) {
  const rows = Object.entries(plats).map(([cls, row]) => {
    const parts = [];
    if (row.base) parts.push(`base: ${JSON.stringify(row.base)}`);
    if (row.upgrades) {
      const ups = Object.entries(row.upgrades).map(([id, l]) => `   "${id}": ${JSON.stringify(l)}`).join(',\n');
      parts.push(`upgrades: {\n${ups}\n  }`);
    }
    return ` ${JSON.stringify(cls)}: {\n  ${parts.join(',\n  ')}\n }`;
  });
  return `/**
 * Generated by tools/furniture-plats/build.mjs from glitch-GameServerJS items/<class>.js
 * getFurnitureBaseGeo and items/catalog_furniture.js (CC0), with the art's foot and cx from
 * tools/furniture-upgrades/render.py. Do not edit by hand.
 *
 * FURNITURE_PLATS[class] = { base: lines, upgrades: { [upgrade_id]: lines } }: the plats a placed
 * piece adds to the room for players to stand on (#772), platform_pc_perm -1 only. A line is
 * [x1, y1, x2, y2] in px from the drawn art's bottom centre, facing right; an upgrade the remake
 * draws with no lines here has none.
 */

export const FURNITURE_PLATS = Object.freeze({
${rows.join(',\n')}
});

export const FURNITURE_PLAT_COUNTS = Object.freeze(${JSON.stringify(counts)});

/** Pieces with standable plats but no measured art to place them by ("<class>/<upgrade id>", 0 the plain piece). */
export const FURNITURE_PLATS_UNMEASURED = Object.freeze(${JSON.stringify(unmeasured)});
`;
}

async function main() {
  const check = process.argv.includes('--check');
  if (!existsSync(GSJS)) {
    console.log(`skip: ${GSJS} not found`);
    return;
  }
  const result = await build();
  const text = render(result);
  if (check) {
    if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) {
      console.error(`${relative(root, OUT)} is stale: run node tools/furniture-plats/build.mjs`);
      process.exit(1);
    }
    console.log(`ok: ${JSON.stringify(result.counts)}`);
    return;
  }
  writeFileSync(OUT, text);
  console.log(JSON.stringify(result.counts), `unmeasured ${result.unmeasured.length}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
