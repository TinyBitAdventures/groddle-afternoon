/**
 * Door keys shared between real players (#157, Austin 2026-11-09: "shared key, 5 minutes"): what
 * the realtime server's keys.go needs. From the game's own table (public/js/door-key-spawns.js
 * KEY_SPAWNS, where each key lay, from the wiki and forum): every spot as [street, x, y, key] in
 * the table's order (the spot's index is the id client and server share) and the respawn.
 *
 * Run from the game repo root:
 *   node tools/build-realtime-door-keys.mjs          (write)
 *   node tools/build-realtime-door-keys.mjs --check  (fail when stale)
 * Writes data/door-keys.json in the realtime server repo (go:embed in its keys.go;
 * found by tools/repos.mjs: GRODDLE_SERVER_DIR, else ../groddle-afternoon-server).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { KEY_RESPAWN_MS, KEY_SPAWNS } from '../public/js/door-key-spawns.js?v=8e6b40bb';

const outPath = serverPath('data', 'door-keys.json');

export function doorKeysData() {
  return {
    about: 'Door key spots for keys.go in groddle-afternoon-server. Generated by tools/build-realtime-door-keys.mjs from public/js/door-key-spawns.js (KEY_SPAWNS); do not edit by hand.',
    format: 'spots[i] = [street, x, y, key]: screen-space feet of the key lying there, door_key_<key>; i is the spot id; respawn in seconds after a pickup',
    respawn: Math.round(KEY_RESPAWN_MS / 1000),
    spots: KEY_SPAWNS.map((s) => [s.street, s.x, s.y, s.key]),
  };
}

async function main() {
  requireServer();
  const out = doorKeysData();
  const text = `${JSON.stringify(out)}\n`;
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-door-keys.mjs`);
      process.exit(1);
    }
    console.log(`${outPath} is current (${out.spots.length} spots)`);
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`${out.spots.length} spots -> ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
