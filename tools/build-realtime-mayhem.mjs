/**
 * G397: what the realtime server's mayhem.go needs to run Math Mayhem
 * between real players, from the game's own rules (js/math-mayhem.js) and
 * the arena Game of Crowns already shares (js/game-of-crowns.js; both games
 * play on LHV2H026E492IAF, config_prod.js 1281-1282):
 *   - the arena street and its four starts (the seats past four spread out
 *     beside them, MAYHEM_SPREAD);
 *   - the touch reach (crowns-feature's tag reach, CROWNS_TAG_DISTANCE and
 *     CROWNS_TAG_REACH_Y: a touch is the same meeting of two avatars);
 *   - the rules: 4 to 20 players, the 10-100 target, the 1 s lock after a
 *     sum, the 4 s countdown, the round's clock (ours), the two teams and
 *     the winner's 200 iMG and 50 currants.
 *
 * Run from the game repo root:
 *   node tools/build-realtime-mayhem.mjs          (write)
 *   node tools/build-realtime-mayhem.mjs --check  (fail when stale)
 * Writes data/mayhem.json in the realtime server repo (go:embed in its
 * mayhem.go; found by tools/repos.mjs: GRODDLE_SERVER_DIR, else
 * ../groddle-afternoon-server).
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { requireServer, serverPath } from './repos.mjs';

import { CROWNS_START_POINTS, CROWNS_STREET, CROWNS_TAG_DISTANCE, CROWNS_TAG_REACH_Y } from '../public/js/game-of-crowns.js?v=e32f35f5';
import {
  MAYHEM_COUNTDOWN_MS,
  MAYHEM_LOCK_MS,
  MAYHEM_PLAYERS,
  MAYHEM_ROUND_MS,
  MAYHEM_SPREAD,
  MAYHEM_TARGET,
  MAYHEM_TEAMS,
  MAYHEM_TITLE,
  MAYHEM_WIN_REWARD,
} from '../public/js/math-mayhem.js?v=7fe952aa';

const outPath = serverPath('data', 'mayhem.json');

export function mayhemData() {
  return {
    about: 'The Math Mayhem rules for mayhem.go in groddle-afternoon-server. Generated by tools/build-realtime-mayhem.mjs from public/js/math-mayhem.js and public/js/game-of-crowns.js; do not edit by hand.',
    format: 'screen coords of the arena street; ms; players {min,max}; target {min,max}; reward {xp,currants}',
    street: CROWNS_STREET,
    title: MAYHEM_TITLE,
    starts: CROWNS_START_POINTS.map((p) => [Math.round(p.x), Math.round(p.y)]),
    spread: MAYHEM_SPREAD,
    touch: { x: CROWNS_TAG_DISTANCE, y: CROWNS_TAG_REACH_Y },
    lockMs: MAYHEM_LOCK_MS,
    countdownMs: MAYHEM_COUNTDOWN_MS,
    roundMs: MAYHEM_ROUND_MS,
    players: { min: MAYHEM_PLAYERS.min, max: MAYHEM_PLAYERS.max },
    target: { min: MAYHEM_TARGET.min, max: MAYHEM_TARGET.max },
    teams: MAYHEM_TEAMS.map((t) => t.id),
    reward: { xp: MAYHEM_WIN_REWARD.xp, currants: MAYHEM_WIN_REWARD.currants },
  };
}

export function mayhemJson() {
  return `${JSON.stringify(mayhemData())}\n`;
}

async function main() {
  requireServer();
  const text = mayhemJson();
  if (process.argv.includes('--check')) {
    const now = await readFile(outPath, 'utf8').catch(() => '');
    if (now !== text) {
      console.error(`${outPath} is stale: run node tools/build-realtime-mayhem.mjs`);
      process.exit(1);
    }
    console.log('mayhem.json is current');
    return;
  }
  await mkdir(dirname(outPath), { recursive: true });
  await writeFile(outPath, text);
  console.log(`wrote ${outPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
