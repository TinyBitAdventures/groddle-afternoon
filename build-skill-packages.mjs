/**
 * Build the skill package table from Tiny Speck's GameServerJS sources.
 *
 * Reads:
 *   items/catalog_skill_packages.js   every skill package (per-rank timing,
 *                                     success, costs, rewards, drops, bonuses)
 *
 * Writes:
 *   public/js/skill-packages-data.js  frozen ES module (pure rule modules
 *                                     import it synchronously)
 *
 * Field names stay exactly as the source spells them (energy_cost,
 * xp_bonus, bonus_chance, ...). `rank` is normalised to a number; the
 * source mixes "1" strings with the -1 no_skill sentinel. The source file is
 * evaluated in a node:vm sandbox; nothing from the Rhino host runs.
 *
 * Run from spike root:
 *   node build-skill-packages.mjs
 */

import vm from 'node:vm';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const GSJS =
  process.env.GLITCH_GSJS ||
  join(process.env.HOME || '', 'Documents/glitch-audit/glitch-GameServerJS');
const SOURCE = join(GSJS, 'items/catalog_skill_packages.js');
const OUT = join(root, 'public/js/skill-packages-data.js');

const ctx = {};
vm.createContext(ctx);
vm.runInContext(readFileSync(SOURCE, 'utf8'), ctx);
const raw = ctx.skill_packages;
if (!raw || typeof raw !== 'object') throw new Error('skill_packages not found in source');

function cleanRow(row) {
  const out = {};
  for (const [key, value] of Object.entries(row || {})) {
    if (key === 'rank') {
      out.rank = Number(value);
      continue;
    }
    out[key] = value;
  }
  return out;
}

const packages = {};
for (const [id, pkg] of Object.entries(raw)) {
  const skills = {};
  for (const [skillId, row] of Object.entries(pkg.skills || {})) skills[skillId] = cleanRow(row);
  const imgUpgrades = {};
  for (const [upgradeId, row] of Object.entries(pkg.img_upgrades || {})) {
    imgUpgrades[upgradeId] = { ...row, rank: String(row.rank) };
  }
  packages[id] = { name: pkg.name || id, skills, img_upgrades: imgUpgrades };
}

const body = `/**
 * GENERATED by build-skill-packages.mjs from GameServerJS
 * items/catalog_skill_packages.js. Do not edit by hand; re-run the builder.
 * ${Object.keys(packages).length} packages.
 */

function deepFreeze(value) {
  if (value && typeof value === 'object') {
    for (const child of Object.values(value)) deepFreeze(child);
    Object.freeze(value);
  }
  return value;
}

export const SKILL_PACKAGES = deepFreeze(${JSON.stringify(packages, null, 2)});
`;

writeFileSync(OUT, body);
console.log(`wrote ${Object.keys(packages).length} skill packages to ${OUT}`);
