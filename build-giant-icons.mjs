/**
 * Build the Giant Icon catalog from Tiny Speck's GameServerJS (CC0).
 *
 * Reads:
 *   items/icon_<giant>.js     label, description, actions_capacity
 *   items/emblem_<giant>.js   emblem label (iconize/caress/consider/contemplate)
 *
 * The Icons' conversations ("Voices/Rituals/Books/Facts of the Giants") are
 * not here: since G202 they come from tools/build-conversations.mjs into
 * public/js/conversations-data.js with every other teller's (G214 dropped the
 * copy; tests/giant-icons.test.js parses the GSJS files to check that data).
 *
 * Writes:
 *   public/js/giant-icons-data.js   frozen ES module
 *
 * Run from spike root:
 *   node build-giant-icons.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const AUDIT = join(process.env.HOME || '', 'Documents/glitch-audit');
const GSJS = process.env.GLITCH_GSJS || join(AUDIT, 'glitch-GameServerJS');
const OUT = join(root, 'public/js/giant-icons-data.js');

// Emblem giant id -> icon class suffix (emblem_base iconize: ti becomes tii).
const GIANTS = ['alph', 'cosma', 'friendly', 'grendaline', 'humbaba', 'lem', 'mab', 'pot', 'spriggan', 'ti', 'zille'];
const iconSuffix = (g) => (g === 'ti' ? 'tii' : g);

const unq = (s) => s.replace(/\\\//g, '/').replace(/\\"/g, '"').replace(/\\'/g, "'").replace(/\\n/g, '\n');
const strVar = (src, name) => {
  const m = src.match(new RegExp(`^var ${name} = "((?:[^"\\\\]|\\\\.)*)";`, 'm'));
  return m ? unq(m[1]) : '';
};

const icons = {};
for (const giant of GIANTS) {
  const iconClass = `icon_${iconSuffix(giant)}`;
  const src = readFileSync(join(GSJS, 'items', `${iconClass}.js`), 'utf8');
  const emblemSrc = readFileSync(join(GSJS, 'items', `emblem_${giant}.js`), 'utf8');
  const capacity = Number(src.match(/"actions_capacity"\s*:\s*"(\d+)"/)?.[1] || 0);
  icons[giant] = {
    giant,
    iconClass,
    emblemClass: `emblem_${giant}`,
    label: strVar(src, 'label'),
    namePlural: strVar(src, 'name_plural'),
    desc: strVar(src, 'description'),
    emblemLabel: strVar(emblemSrc, 'label'),
    emblemPlural: strVar(emblemSrc, 'name_plural'),
    capacity,
  };
}

const header = `/**
 * GENERATED by build-giant-icons.mjs from GameServerJS items/icon_*.js and
 * items/emblem_*.js (Tiny Speck, CC0). Do not edit by hand.
 */

`;
writeFileSync(OUT, `${header}export const GIANT_ICON_DATA = Object.freeze(${JSON.stringify(icons, null, 2)});\n`);
console.log(`wrote ${OUT}: ${Object.keys(icons).length} icons`);
