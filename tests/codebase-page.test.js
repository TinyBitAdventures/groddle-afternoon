/** The Code page (/code/): its data is current and honest, and the page, block and styles agree with it. */

import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { LANGUAGES, countLines, saysGenerated } from '../tools/codebase/build-data.mjs';
import { codebaseContent } from '../tools/codebase/to-minn.mjs';
import { GAME_DIR, sitePath, skipWithoutServer, skipWithoutSite } from '../tools/repos.mjs';

const skip = skipWithoutSite || skipWithoutServer;
const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const sum = (rows, key = 'lines') => rows.reduce((n, r) => n + r[key], 0);

describe('Code page data (tools/codebase/build-data.mjs)', () => {
  it('is current: data.json matches a fresh measure of the live tags', { skip }, () => {
    execFileSync(process.execPath, [join(GAME_DIR, 'tools/codebase/build-data.mjs'), '--check'], { stdio: 'pipe' });
  });

  it('measures each repo at the tag live.json names, and its parts add up', { skip }, () => {
    const live = readJson(join(GAME_DIR, 'tools/deploy/live.json'));
    const d = readJson(join(GAME_DIR, 'public/codebase/data.json'));
    assert.deepEqual(d.repos.map((r) => r.id), ['game', 'server', 'site']);
    assert.deepEqual(d.repos.map((r) => r.ref), [live.game, live.server, live.site]);
    assert.equal(d.platform.engine.commit, live.engine.slice(0, 8));
    assert.equal(d.platform.minnAdmin.commit, live.minnAdmin.slice(0, 8));
    const ids = LANGUAGES.map(([id]) => id);
    for (const r of d.repos) {
      assert.equal(r.url, `https://github.com/TinyBitAdventures/${r.name}`);
      assert.equal(r.licence, 'MIT');
      assert.equal(sum(r.languages), r.code.lines, `${r.id} languages`);
      assert.equal(sum(r.languages, 'files'), r.code.files, `${r.id} language files`);
      assert.equal(sum(r.areas), r.code.lines, `${r.id} areas`);
      assert.equal(sum(r.areas, 'files'), r.code.files, `${r.id} area files`);
      assert.equal(r.code.files + sum(r.notCode, 'files'), r.totalFiles, `${r.id} every file is code or listed beside it`);
      for (const l of r.languages) assert.ok(ids.includes(l.id), l.id);
      assert.ok(r.tests.cases > 0 && r.tests.files > 0, `${r.id} tests`);
      assert.ok(r.history.commits > 0 && r.history.first <= r.history.latest, `${r.id} history`);
    }
    const game = d.repos[0];
    // The minified PixiJS and the built item pages are listed, never counted as code.
    assert.ok(game.notCode.some((n) => n.id === 'vendored'));
    assert.ok(game.notCode.some((n) => n.id === 'generated' && n.files > 900));
    assert.ok(!game.largest.some((f) => f.path.startsWith('public/vendor/') || f.path.startsWith('public/items/')));
  });

  it('counts lines and spots generated files by their header', () => {
    assert.equal(countLines(Buffer.from('')), 0);
    assert.equal(countLines(Buffer.from('a')), 1);
    assert.equal(countLines(Buffer.from('a\n\nb\n')), 3);
    assert.equal(saysGenerated('/**\n * GENERATED by build-drop-tables.mjs from GameServerJS\n */'), true);
    assert.equal(saysGenerated('// Generated by tools/room-art/build.py (x).\n// Do not edit.'), true);
    assert.equal(saysGenerated('<!doctype html>\n<!-- Generated from play/index.html by tools/play-online/build.mjs: edit that page or the builder, never this file. -->'), true);
    // A note that some other file is generated does not make this one generated.
    assert.equal(saysGenerated('/**\n * Fetch and cache street JSON.\n * Index is generated by scripts/import-locations-xml.mjs.\n */'), false);
    assert.equal(saysGenerated('/**\n * Capacities come from the generated Tiny Speck item classes.\n */'), false);
  });
});

describe('Code page in Minn (tools/codebase/to-minn.mjs)', () => {
  const content = codebaseContent();

  it('draws every figure from the groddle/codebase block, one per section', () => {
    for (const repo of ['overview', 'game', 'server', 'site', 'platform']) {
      assert.equal(content.split(`<!-- wp:groddle/codebase {"repo":"${repo}"} /-->`).length, 2, repo);
    }
    // No figure is typed into the words: the only digits are in version-free names and examples.
    const words = content.replace(/<!--[\s\S]*?-->/g, '').replace(/<[^>]+>/g, ' ');
    assert.doesNotMatch(words, /\b\d{2,}(?:,\d{3})*\s+(?:lines|files|tests|commits)\b/);
  });

  it('links each repo, its issues and pull requests, and keeps the house style', () => {
    for (const repo of ['groddle-afternoon', 'groddle-afternoon-server', 'groddle-afternoon-site']) {
      for (const tail of ['', '/issues', '/pulls']) assert.ok(content.includes(`https://github.com/TinyBitAdventures/${repo}${tail}"`), `${repo}${tail}`);
    }
    assert.ok(content.includes('https://github.com/austinginder/minn-engine'));
    assert.ok(content.includes('https://github.com/tinyspeck'));
    assert.doesNotMatch(content, /—/, 'no em-dashes in page copy');
  });

  it('is wired into the site: block.json, minn.json, the extension and the styles', { skip: skipWithoutSite }, () => {
    const block = readJson(sitePath('blocks/codebase/block.json'));
    assert.equal(block.name, 'groddle/codebase');
    assert.deepEqual(block.attributes.repo.enum, ['overview', 'game', 'server', 'site', 'platform']);
    assert.ok(readJson(sitePath('minn.json')).blocks.includes('groddle/codebase'));
    assert.match(readFileSync(sitePath('src/Extension.php'), 'utf8'), /Codebase::register\(\$minn, \$root\);/);
    const php = readFileSync(sitePath('src/Codebase.php'), 'utf8');
    const order = /ORDER = \[([^\]]*)\]/.exec(php)[1].match(/'([a-z]+)'/g).map((s) => s.slice(1, -1));
    assert.deepEqual(order, LANGUAGES.map(([id]) => id), 'the bar order is the builder\'s language order');
    const css = readFileSync(sitePath('style.css'), 'utf8');
    const themes = css.split('\n').filter((line) => line.includes('--cb-javascript:'));
    assert.equal(themes.length, 3, 'light, dark by system, dark by choice');
    for (const line of themes) for (const id of [...order, 'other']) assert.match(line, new RegExp(`--cb-${id}: #[0-9a-f]{6};`), id);
  });
});
