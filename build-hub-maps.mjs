/**
 * Writes public/js/hub-maps-data.js: the streets each hub's map lists, as the
 * remake's G-prefixed tsids. Source: glitch-GameServerJS/inc_data_maps_prod.js
 * maps_get_streets() (mote id -> hub id -> { L-tsid: public name }), the same
 * map data locations/location.js countsTowardHubAchievement walks
 * (config.data_maps.maps[hubid].objs) before a street counts toward a hub's
 * Completist badge.
 *
 * Published zones (level builder, docs/level-builder/spec.md 11, 15 Q5) are
 * never added: they stay off the world map and out of Completist badges. Their
 * own hub maps come from tools/builder/build-zone-maps.mjs.
 *
 *   node build-hub-maps.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const here = dirname(fileURLToPath(import.meta.url));
const gsjs = join(here, '..', 'glitch-GameServerJS');
const out = join(here, 'public', 'js', 'hub-maps-data.js');

const sandbox = { config: {}, log: { info() {}, error() {} } };
vm.runInNewContext(`${await readFile(join(gsjs, 'inc_data_maps_prod.js'), 'utf8')}\nthis.streets = maps_get_streets();`, sandbox);

const hubs = {};
for (const moteHubs of Object.values(sandbox.streets || {})) {
  for (const [hubId, streets] of Object.entries(moteHubs || {})) {
    for (const tsid of Object.keys(streets || {})) {
      if (typeof streets[tsid] !== 'string') continue;
      (hubs[hubId] ||= new Set()).add(`G${tsid.slice(1)}`);
    }
  }
}

const sorted = Object.fromEntries(
  Object.keys(hubs).sort((a, b) => Number(a) - Number(b)).map((id) => [id, [...hubs[id]].sort()])
);
const body = `/**
 * GENERATED by build-hub-maps.mjs from inc_data_maps_prod.js maps_get_streets().
 * Hub id -> the streets its map lists (G-prefixed tsids). A street counts
 * toward its hub's Completist badge only when the hub map lists it
 * (locations/location.js countsTowardHubAchievement).
 */
export const HUB_MAP_STREETS = Object.freeze(${JSON.stringify(sorted)});
`;
await writeFile(out, body);
console.log(`${Object.keys(sorted).length} hubs, ${Object.values(sorted).reduce((n, s) => n + s.length, 0)} streets -> ${out}`);
