/**
 * Shared drop tables (items/catalog_drop_tables.js) and the skill-package
 * drop roll (players/inc_skill_packages.js runSkillPackage + runDropTable).
 *
 * - runDropTable: chance = randInt(0, 100); the first row whose threshold
 *   the roll does not exceed pays every entry in it: items, currants, favor
 *   (one Giant or "all"), mood, energy, iMG, or a nested table (rolled again).
 * - runSkillPackage: when the package row (after imagination overlays) has a
 *   drop_class_id, it drops on is_chance(drop_chance / 100), x1.25 under the
 *   Rubeweed buff (capped at 100%), always under Max Luck.
 * - Activity lines are the source's "You got 3 Planks!" / "You got 11
 *   currants!" / "You got 5 favor with all the Giants!" / "You got 20 mood!".
 *
 * Data: ./drop-tables-data.js (generated by build-drop-tables.mjs).
 */

import { DROP_ITEMS, DROP_TABLES } from './drop-tables-data.js';
import { skillPackageDetails } from './skill-packages.js';
import { grantMoodXp } from './mood-xp.js';

export { DROP_ITEMS, DROP_TABLES };

export const GIANT_IDS = Object.freeze(['alph', 'cosma', 'friendly', 'grendaline', 'humbaba', 'lem', 'mab', 'pot', 'spriggan', 'ti', 'zille']);
const MAX_DEPTH = 8;

/** Source randInt(lo, hi), inclusive. */
const randInt = (lo, hi, rng) => lo + Math.floor(rng() * (hi - lo + 1));

export function createDropResult(tableId = null) {
  return { table: tableId, rolls: [], items: [], currants: 0, favor: [], mood: 0, energy: 0, xp: 0 };
}

/** True when nothing dropped. */
export function isEmptyDrop(result) {
  return !result || (!result.items.length && !result.currants && !result.favor.length && !result.mood && !result.energy && !result.xp);
}

/**
 * runDropTable: one roll on a table, nested tables rolled in turn.
 * Mutates and returns `out` (a createDropResult()).
 */
export function rollDropTable(tableId, rng = Math.random, out = createDropResult(tableId), depth = 0) {
  const table = DROP_TABLES[tableId];
  if (!table || depth > MAX_DEPTH) return out;
  const chance = randInt(0, 100, rng);
  out.rolls.push({ table: tableId, roll: chance });
  for (const [threshold, entries] of table.rows) {
    if (chance > threshold) continue;
    for (const e of entries) {
      if (e.item) out.items.push({ classTsid: e.item, qty: e.count || 1, table: tableId });
      else if (e.currants) out.currants += e.currants;
      else if (e.favor) out.favor.push({ giant: e.favor.giant, points: e.favor.points });
      else if (e.mood) out.mood += e.mood;
      else if (e.energy) out.energy += e.energy;
      else if (e.xp) out.xp += e.xp;
      else if (e.table) rollDropTable(e.table, rng, out, depth + 1);
    }
    return out;
  }
  return out;
}

/**
 * The drop chance (percent) a package gives this player: the qualifying row
 * plus imagination overlays, x1.25 under Rubeweed, capped at 100.
 * Returns { tableId, chance, details } or null when the package never drops.
 */
export function packageDropChance(packageId, learned = [], upgrades = [], { rubeweed = false } = {}) {
  const details = skillPackageDetails(packageId, learned, upgrades);
  if (!details?.drop_class_id) return null;
  let chance = Number(details.drop_chance) || 0;
  if (rubeweed) chance *= 1.25;
  return { tableId: details.drop_class_id, chance: Math.min(100, chance), details };
}

/**
 * runSkillPackage's drop step for one successful action.
 * ctx: { learned, upgrades, rubeweed, maxLuck, rng }
 * Returns { hit, packageId, tableId, chance, result }.
 */
export function rollPackageDrop(packageId, ctx = {}) {
  const rng = ctx.rng || Math.random;
  const odds = packageDropChance(packageId, ctx.learned, ctx.upgrades, ctx);
  if (!odds) return { hit: false, packageId, tableId: null, chance: 0, result: null };
  const hit = ctx.maxLuck === true || rng() < odds.chance / 100;
  return {
    hit,
    packageId,
    tableId: odds.tableId,
    chance: odds.chance,
    result: hit ? rollDropTable(odds.tableId, rng) : null,
  };
}

const capitalize = (s) => String(s || '').charAt(0).toUpperCase() + String(s || '').slice(1);
const pluralize = (n, single, plural) => (n === 1 ? `1 ${single}` : `${n} ${plural}`);

export function dropItemName(classTsid, qty, meta = DROP_ITEMS[classTsid]) {
  return pluralize(qty, meta?.single || classTsid, meta?.plural || `${classTsid}s`);
}

/**
 * Pay a drop result into the pack and stats. `favorCap(giant)` caps a
 * Giant's favor (the shrine emblem target); `favor` is the per-Giant ledger.
 * Returns the source activity lines and what actually landed.
 * target: { inv, pc, favor, favorCap, energyCap, moodCap, addItem }
 */
export function applyDropResult(result, target = {}) {
  const lines = [];
  const landed = { items: [], currants: 0, favor: 0, mood: 0, energy: 0, xp: 0 };
  if (!result) return { lines, landed };
  const { inv, pc } = target;
  for (const it of result.items) {
    if (typeof target.addItem === 'function') target.addItem(inv, it.classTsid, it.qty);
    else if (inv) inv[it.classTsid] = (Number(inv[it.classTsid]) || 0) + it.qty;
    landed.items.push({ classTsid: it.classTsid, qty: it.qty });
    lines.push(`You got ${dropItemName(it.classTsid, it.qty)}!`);
  }
  if (result.currants && pc) {
    pc.currants = (Number(pc.currants) || 0) + result.currants;
    landed.currants = result.currants;
    lines.push(`You got ${pluralize(result.currants, 'currant', 'currants')}!`);
  }
  for (const f of result.favor) {
    const giants = f.giant === 'all' ? GIANT_IDS : [f.giant];
    let total = 0;
    if (target.favor) {
      for (const g of giants) {
        const before = Number(target.favor[g]) || 0;
        const cap = typeof target.favorCap === 'function' ? target.favorCap(g) : Infinity;
        target.favor[g] = Math.min(cap, before + f.points);
        total += target.favor[g] - before;
      }
    }
    landed.favor += total;
    lines.push(`You got ${f.points} favor with ${f.giant === 'all' ? 'all the Giants' : capitalize(f.giant)}!`);
  }
  if (result.mood && pc) {
    const cap = target.moodCap ?? 100;
    const before = Number(pc.mood) || 0;
    pc.mood = Math.min(cap, before + result.mood);
    landed.mood = Math.round(pc.mood - before);
    lines.push(`You got ${landed.mood} mood!`);
  }
  if (result.energy && pc) {
    const cap = target.energyCap ?? 100;
    const before = Number(pc.energy) || 0;
    pc.energy = Math.min(cap, before + result.energy);
    landed.energy = Math.round(pc.energy - before);
    lines.push(`You got ${landed.energy} energy!`);
  }
  if (result.xp && pc) {
    // runDropTable (inc_skill_packages.js 106): stats_add_xp(it.xp, false), and
    // "You got N iMG!" names what landed.
    landed.xp = grantMoodXp(pc, result.xp);
    lines.push(`You got ${landed.xp} iMG!`);
  }
  return { lines, landed };
}

/** Odds that a table hands out a given item (one roll, nested tables included). */
export function tableItemOdds(tableId, classTsid, depth = 0) {
  const table = DROP_TABLES[tableId];
  if (!table || depth > MAX_DEPTH) return 0;
  let prev = -1;
  let odds = 0;
  for (const [threshold, entries] of table.rows) {
    const width = (Math.min(100, threshold) - prev) / 101;
    prev = Math.min(100, threshold);
    for (const e of entries) {
      if (e.item === classTsid) odds += width;
      else if (e.table) odds += width * tableItemOdds(e.table, classTsid, depth + 1);
    }
  }
  return odds;
}
